/**
 * The arithmetic that was being asked of the model mid-call, done here instead.
 *
 * ── The two live failures this closes ────────────────────────────────────────
 * Both were the same shape: she had the numbers and did not divide.
 *
 *   "four posts, three thousand dollars" and "your rate's two twenty a post"
 *   → "three thousand is comfortably above your usual per-post rate."
 *
 * That compares a TOTAL to a PER-POST rate. It landed directionally right by
 * luck ($750/post really is above $220), and it flips in the ordinary case:
 * $1,200 across six posts is $200 a post, genuinely BELOW $220, and the same
 * method calls it "comfortably above". A confidently wrong money claim, which
 * is the exact failure class the stale-`deals.amount` fix existed to remove.
 *
 *   $500 for ONE post, rate $220 → "the rate is a bit low compared to your
 *   value."
 *
 * There she skipped the arithmetic entirely and read `rateComparison` aloud —
 * and the arithmetic contradicted it.
 *
 * ── Why `rateComparison` can be wrong, which is the deeper point ─────────────
 * It LOOKS like the rate-card comparison and is not. `factorRatings` is Kimi's
 * own output (`fr = parsed.factorRatings`, server/skills/dealDetector.ts), so
 * `rateComparison` is a MODEL JUDGMENT read off the email text, enum-validated
 * on the way in. The deterministic, rate-card-aware money read is
 * gone with the retired deal score; nothing here compares against a rate card any more.
 *
 * So the wire carried an opinion about the rate and never the division. This
 * gives the model the number so it stops guessing at one, and so a grade that
 * disagrees with plain arithmetic can be recognised as the softer signal.
 *
 * ── Unit-awareness is not optional, and is reused rather than restated ───────
 * `matchRate` (server/skills/dealScoreGrid.ts) already maps unit → what the
 * per-unit figure even MEANS: `per_post` is already per-unit, `total` divides by
 * the deliverable count, `per_appearance` compares against an appearance fee,
 * `monthly`/`annual` annualize into PAV. Dividing without it would reproduce the
 * category error in a different costume.
 *
 * Her per-post RATE is no longer compared: the legacy rate card is retired (8 Oct 2026), so
 * `athleteRate` and `rateMultiple` are always null — the wire keeps both fields so the voice
 * worker's contract does not change. Only the per-deliverable figure crosses.
 */
export interface VoiceRateRead {
  /** What one post/reel is worth under this deal, whole dollars. */
  perDeliverable: number | null;
  /** Her own canonical per-post rate — live, never the scorer's snapshot. */
  athleteRate: number | null;
  /** perDeliverable ÷ athleteRate, one decimal. Null unless both are present. */
  rateMultiple: number | null;
}

const EMPTY_RATE_READ: VoiceRateRead = {
  perDeliverable: null,
  athleteRate: null,
  rateMultiple: null,
};

export function resolveRateRead(offer: VoiceOffer): VoiceRateRead {
  // Only a figure we are willing to SPEAK can be divided. On `range`,
  // `unverified` and `unstated` there is no point figure, so there is no
  // honest per-post number either.
  if (offer.moneyState !== "stated" || offer.amount === null) {
    return EMPTY_RATE_READ;
  }

  const matched = matchRate({
    amount: offer.amount,
    unit: offer.unit,
    deliverable_counts: offer.deliverables ?? null,
  });

  // `socialPost` ONLY: a per-post figure is what "that's five hundred a post" means; an appearance fee or an
  // annualized figure is a different quantity.
  if (!matched || matched.key !== "socialPost") return EMPTY_RATE_READ;

  const perDeliverable = money(Math.round(matched.perUnit));
  if (perDeliverable === null) return EMPTY_RATE_READ;
  // No computed rate to compare against (the legacy rate card is retired): the figure alone.
  return { ...EMPTY_RATE_READ, perDeliverable };
}
