/**
 * studio/agent/eval/census/verdicts — ONE VERDICT PER CENSUS ROW, with its cite (PR 16, R-3).
 *
 *   CONSUMED          reaches a model prompt or an artifact that decides an output. With `check: "flow"`,
 *                     `at` names the consuming points it must reach (flags on) and `offAt` flags off; the
 *                     census reds by name when it stops reaching one.
 *   DECIDES           changes a branch — `cite` names the branch, `reads` the token the reader holds.
 *   DISPLAY           client-only by design — `cite` names the display reader.
 *   DELIBERATE-DEAD   dead on purpose — `cite` MUST name the ruling (a ledger line, ADI-24SEP, or a code
 *                     comment that states the ruling). No cite, no DELIBERATE-DEAD (rows.test).
 *   DEAD              carried by nothing, no ruling — a FINDING, with the owner it is carded to.
 *
 * A row absent from this table is UNVERDICTED and fails the census (rows.test): adding a field to any
 * census source without wiring it and classifying it breaks a test. That is the point.
 */
import type { Point } from "./capture";

export type Verdict =
  | "CONSUMED"
  | "DECIDES"
  | "DISPLAY"
  | "DELIBERATE-DEAD"
  | "DEAD";

export interface RowVerdict {
  /** The verdict with every Studio flag on. */
  v: Verdict;
  /** The verdict in the pre-roadmap baseline (the six gates off), when it differs. */
  off?: Verdict;
  /**
   * How the verdict is held: `flow` — measured by the census flows; `unit` — by capabilities.test;
   * `static` — the cited reader still holds `reads`; `cite` — not measurable here, held by its cite.
   */
  check: "flow" | "unit" | "static" | "cite";
  /** CONSUMED + flow: the consuming points it must reach, flags on. */
  at?: Point[];
  /** CONSUMED + flow: the same, flags off (defaults to `at` when `off` is unset or CONSUMED). */
  offAt?: Point[];
  /** Where the verdict comes from: the reader or branch (file:line), or the ruling. */
  cite: string;
  /** static: a token the cited reader must still contain (a field name, as the code spells it). */
  reads?: string;
  /** DEAD: the card and the PR it is proposed to. */
  owner?: string;
}

