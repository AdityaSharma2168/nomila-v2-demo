/**
 * videoEntryLogic — what a VIDEO ENTRY looks like, as arithmetic.
 *
 * ─── A VIDEO ENTRY IS A VIDEO, NOT A GENERATION RESULT ──────────────────────────────────────────
 *
 * ⚠️ THE LOAD-BEARING DECISION IN THIS FILE. An entry is keyed on "this is a video", never on
 * "this came out of a generation job". A clip she uploaded is a video entry; a clip Veo made is a
 * video entry; both render and play identically, because to the person looking at it the only
 * thing that matters is that it is a video.
 *
 * That is not speculative generality — two product pipelines are coming (upload → stitch → music,
 * and generate-from-keyframes) and both produce entries that belong on the same surface. A
 * renderer that assumed "entry = job output" would have to be rewritten for each of them.
 *
 * So the shape below is the source-agnostic core, and knowing about a generation job is an
 * ADAPTER: `videoEntryFromJob`. Another pipeline adds its own adapter beside it and reuses
 * everything else — the view, the component, the player. Nothing downstream of `VideoEntryView`
 * knows where the clips came from, and nothing may start to.
 *
 * ─── WHY THIS IS PURE ───────────────────────────────────────────────────────────────────────────
 *
 * Everything here is a function of its arguments. No React, no navigation, no fetch. That is what
 * lets the same view model be drawn by the provisional Video tab today and by MadeShelf /
 * ThreadCards later WITHOUT being rewritten — the move is a re-mount, because the thinking never
 * lived in the screen.
 *
 * The ARITHMETIC is here and is pinned by pure tests; the WIRING — a watch that must settle once
 * and then stop — is pinned by a real mounted hook in use-studio-sessions.watch.test.tsx. Neither
 * test covers the other's half.
 *
 * ─── GENERATED VIDEO IS DARK ────────────────────────────────────────────────────────────────────
 *
 * `STUDIO_VIDEO_ENABLED` is off by default (server/studio/config.ts), so the generation adapter has
 * never met a real clip. Every test against it drives stubbed job rows in each status. Anything
 * needing a real Veo mp4 — that it decodes, that it plays — is "verifiable only after flag-flip"
 * and is not asserted. The source-agnostic core has no such caveat: an uploaded clip is real today.
 */
import {
  outputFromRun,
  pollProgress,
  type JobRead,
  type OutputView,
} from "./threadLogic";

/**
 * WHERE AN ENTRY IS IN ITS OWN PIPELINE — deliberately pipeline-NEUTRAL words.
 *
 *   queued   the work is owed and nothing has started it yet. A generation job waiting for a
 *            runner is queued; so is a clip waiting for a stitch.
 *   working  something is actively producing it.
 *   ready    there are clips, and they can be played. An upload that is simply stored is born
 *            here, with no preceding phase at all.
 *   failed   it will not arrive.
 *   unknown  we have lost track of it. Distinct from `failed`: nothing says it went wrong, only
 *            that we stopped being able to tell.
 *
 * `queued` and `working` are both "still going" and are kept apart on purpose: watching that
 * transition is the entire reason the provisional Video tab exists, and one pulse cannot show it.
 * The thread's LoadingTile has no input but its own animation — right for an image, which is
 * already generated by the time the tile renders, useless for a clip a runner picks up ~63 s later.
 */
export type VideoEntryPhase =
  | "queued"
  | "working"
  | "ready"
  | "failed"
  | "unknown";

export interface VideoEntryView {
  phase: VideoEntryPhase;
  /** ⚠️ PLACEHOLDER WORDING, for the copy-review pile (Mia). */
  label: string;
  /** True while the entry is still expected to change on its own. */
  working: boolean;
  /**
   * The clips. `OutputView` is already source-agnostic — ThreadCards builds one from a stored
   * asset (`outputFromAsset`) and one from a run (`outputFromRun`) — so an upload pipeline adds a
   * constructor, not a type.
   */
  clips: OutputView[];
}

/** ⚠️ PLACEHOLDER WORDING, for the copy-review pile (Mia). */
const LABEL: Record<VideoEntryPhase, string> = {
  queued: "Queued — waiting for a slot",
  working: "Making it…",
  ready: "Ready",
  failed: "That one didn't work",
  unknown: "We lost track of this one",
};

/**
 * THE SOURCE-AGNOSTIC CORE. A phase and some clips; no job, no route, no opinion about origin.
 * Every pipeline's adapter ends here.
 */
export function videoEntry(
  phase: VideoEntryPhase,
  clips: OutputView[] = [],
): VideoEntryView {
  const working = phase === "queued" || phase === "working";
  return { phase, label: LABEL[phase], working, clips: working ? [] : clips };
}

/**
 * A video that already exists — an upload, or anything else with bytes and no pipeline left to
 * run. No job is involved and none is invented.
 */
export function readyVideoEntry(clips: OutputView[]): VideoEntryView {
  return videoEntry("ready", clips);
}

/**
 * THE GENERATION ADAPTER — the only function in this file that knows what a generation job is.
 *
 * `outcome` is `pollOutcome`'s verdict, passed in rather than recomputed, so this and the watch can
 * never disagree about whether a run has finished. This decides only how to SHOW what that verdict
 * already established.
 *
 * ⚠️ THE BACK-EDGE. `running → queued` arrives as an ordinary `queued` phase, still working. It is
 * the server's reaper handing a job to another runner with the operation handle intact
 * (studio/videoJobs.ts, reapExpiredLeases step 3) — the clip is still being made and is already
 * paid for. Rendering it as an ending of any kind would be a lie about a healthy system.
 */
export function videoEntryFromJob(
  read: JobRead | "missing" | "error",
  outcome: "continue" | "made" | "failed" | "stalled",
): VideoEntryView {
  const readable = read !== "missing" && read !== "error";
  if (outcome === "made")
    return videoEntry("ready", readable ? read.assets.map(outputFromRun) : []);
  if (outcome === "failed") return videoEntry("failed");
  if (outcome === "stalled") return videoEntry("unknown");
  // Still going. A read we could not make is NOT progress and must not repaint the entry — it
  // keeps the phase it had, which for a tick that learned nothing is `working`.
  const phase = pollProgress(read);
  return videoEntry(phase === "queued" ? "queued" : "working");
}
