/**
 * draftIntentRoute.ts — voice asks for a draft card. It does NOT draft.
 *
 * POST /athletes/:id/draft-intent, mounted at /api/internal/voice.
 * Trusted infrastructure, secret-guarded, athlete-scoped by the path id.
 *
 * ── Why this route resolves instead of drafting ──────────────────────────────
 * The obvious implementation calls `generateDealDraft` here and hands the copy
 * back. It is wrong twice over.
 *
 * First, cost and correctness: `POST /api/v1/me/deals/:id/draft` ALREADY
 * generates, streams, and is rate-limited, and the client already consumes it
 * (client/hooks/use-deal-draft.ts). If this route generated too, one spoken
 * request would run the model TWICE, produce two different drafts, and throw
 * away the one Mila "made" — because the card renders whatever the client
 * fetched.
 *
 * Second, and the reason this is the trust boundary: a draft is derived from the
 * brand's own email. If it were generated here it would travel back through the
 * worker, into a live model's context, and across a data channel — three places
 * attacker-influenced prose does not belong. Because the draft is generated by
 * the CLIENT, under the athlete's own session, it never enters any of them. That
 * is a property of the shape, not a rule anyone has to remember.
 *
 * So this route does the part the client cannot: decide, athlete-scoped, whether
 * there is a real deal and a real reply path. No model call, no draft text, no
 * prose in or out.
 *
 * ── It creates NO pending action ─────────────────────────────────────────────
 * Same as the text path. The send is propose-at-tap: the client creates a
 * `send_reply` pending action with the CURRENT edited body and approves it, on a
 * deliberate tap. Nothing here moves voice any closer to sending — the athlete's
 * tap remains the only thing that sends, and that path is untouched.
 *
 * ── Persist first, push second ───────────────────────────────────────────────
 * The card is written onto a `chat_message` HERE, before this route answers, so
 * it exists whether or not the live push lands. The row carries a deterministic
 * non-empty line because `getConversationMessages` drops a message with empty
 * content — a blank one would render live and then vanish on reopen.
 */

import { Router, type Request, type Response } from "express";
import { and, desc, eq } from "drizzle-orm";
import { db } from "../db";
import {
  chatMessages,
  deals,
  inboxMessages,
  inboxThreads,
} from "../../shared/schema";
import { upsertConversationOnMessage } from "../mila/conversations";
import { withTimeout } from "../lib/withTimeout";
import { isStructurallySendable } from "../lib/sendGate";
import { createLogger } from "../logger";
import { voiceAuthorized, sendVoiceRefusal, UUID_RE } from "./auth";
import { resolveAthleteDealsByBrand } from "./dealResolver";
import { toolRefusal } from "../agent/welcome/toolGate";

const logger = createLogger("voice/draftIntent");

const router = Router();

/** Bounds the whole thing. This runs inside a live call's tool turn. */
const RESOLVE_TIMEOUT_MS = 4_000;

/** The card the resolve answers with when it landed on exactly one deal. */
interface DraftIntentCard {
  dealId: string;
  threadId: string | null;
  platform: string;
  brandName: string;
  replyIntent: ReplyIntent;
  sendable: boolean;
}

type DraftIntentResult = DraftIntentCard | null;

/** The four things a reply can try to do. Mirrors ReplyIntent. */
const REPLY_INTENTS = [
  "accept",
  "negotiate",
  "request_terms",
  "decline",
] as const;
type ReplyIntent = (typeof REPLY_INTENTS)[number];

// The platform allow-list and the gate itself now live in ../lib/sendGate, shared
// with the text tool and the text card builder. This route used to keep its own
// copy; the copy in widgets.ts is the one that drifted, and the warning on
// resolveReplyPath below is what predicted it.

const isRecord = (v: unknown): v is Record<string, unknown> =>
  v !== null && typeof v === "object" && !Array.isArray(v);

const intentOf = (v: unknown): ReplyIntent | null =>
  typeof v === "string" && REPLY_INTENTS.some((r) => r === v)
    ? (v as ReplyIntent)
    : null;

/**
 * Resolves the reply path for a deal: the thread to reply into, the platform of
 * its latest INBOUND message, and whether there is an inbound at all.
 *
 * Deliberately the same derivation `draft_reply` uses (server/mila/tools/
 * draftReply.ts) — platform read off the newest inbound row, which is the exact
 * row `sendThreadReply` replies to. If the two disagreed, a card's Send gate
 * would promise something the send route refuses.
 */
async function resolveReplyPath(
  athleteId: string,
  dealId: string,
): Promise<{ threadId: string | null; platform: string; hasInbound: boolean }> {
  const [thread] = await db
    .select({ id: inboxThreads.id })
    .from(inboxThreads)
    .where(
      and(
        eq(inboxThreads.deal_id, dealId),
        eq(inboxThreads.athlete_id, athleteId),
      ),
    )
    .orderBy(desc(inboxThreads.last_message_at))
    .limit(1);

  if (!thread) return { threadId: null, platform: "gmail", hasInbound: false };

  const [lastInbound] = await db
    .select({ platform: inboxMessages.platform })
    .from(inboxMessages)
    .where(
      and(
        eq(inboxMessages.thread_id, thread.id),
        eq(inboxMessages.direction, "inbound"),
      ),
    )
    .orderBy(desc(inboxMessages.received_at))
    .limit(1);

  return {
    threadId: thread.id,
    platform: lastInbound?.platform ?? "gmail",
    hasInbound: Boolean(lastInbound),
  };
}

/**
 * The half that is identical however the deal was found: confirm ownership,
 * decide the structural send gate, persist the card, and return it.
 *
 * Split out when `dealId` targeting landed. Both callers must produce a
 * byte-identical card — a revision that rendered differently from the draft it
 * replaces would be a new bug wearing the old one's clothes — so there is one
 * implementation rather than two that agree today.
 *
 * TENANCY: this re-read is the ONLY authority on ownership. The brand path has
 * already filtered by athlete, but the id path has NOT — a dealId arrives from
 * the worker and is not trusted — so `and(id, athlete_id)` here is what turns
 * another athlete's deal into a null, and a null into a 404.
 */
async function buildCard(
  id: string,
  dealId: string,
  path: Awaited<ReturnType<typeof resolveReplyPath>>,
  replyIntent: ReplyIntent,
  conversationId: string,
  brand = "",
): Promise<DraftIntentCard | null> {
  // Re-read the deal athlete-scoped. The resolver already filtered, but
  // this is the row the card is bound to and it costs one indexed lookup.
  const [owned] = await db
    .select({ id: deals.id, brand_name: deals.brand_name })
    .from(deals)
    .where(and(eq(deals.id, dealId), eq(deals.athlete_id, id)))
    .limit(1);
  if (!owned) return null;

  const { threadId, platform, hasInbound } = path;

  // The STRUCTURAL send gate only: a real reply path exists. The
  // draft-dependent half (clean copy, no refusal) is decided on the client
  // once the body has loaded, because the body does not exist yet here.
  const sendable = isStructurallySendable({
    threadId,
    hasInbound,
    platform,
  });

  const brandName = owned.brand_name ?? brand;

  // ── Persist first ────────────────────────────────────────────────────
  // Written BEFORE this route answers, so the card survives reload whether
  // or not the live push lands. `needsDraft` is what tells the client to
  // generate the body itself; `draft` is null because no draft exists
  // anywhere yet, and that is the whole point of this design.
  const widget = {
    type: "reply_action" as const,
    data: {
      dealId: owned.id,
      threadId,
      platform,
      sendable,
      brandName,
      draft: null,
      refusal: null,
      needsDraft: true,
      params: {
        replyIntent,
        style: "friendly" as const,
        voice: "athlete" as const,
        selectedTerms: [] as string[],
        includeMediaKit: false,
      },
    },
  };

  // Deterministic and non-empty: getConversationMessages drops a message
  // with empty content, and this line is also the honest record of what
  // happened — a card was opened, not a reply written.
  const content = `Draft reply to ${brandName}`;

  await upsertConversationOnMessage(id, conversationId, content);
  await db.insert(chatMessages).values({
    athlete_id: id,
    conversation_id: conversationId,
    role: "assistant",
    content,
    widget,
    source: "voice",
  });

  // `threadId` and `platform` are returned so the LIVE card can be built
  // from the same values as the PERSISTED one above.
  //
  // They were originally omitted as need-to-know, and the worker filled
  // the gap with `threadId: null` — which the client's validator turns
  // into `sendable: false` unconditionally (a card with no thread has
  // nothing to reply into). The effect was a voice card that could never
  // send, disagreeing with the identical card after a reload. Deriving a
  // value on one side of a boundary and reconstructing it on the other is
  // the bug; sending it is the fix.
  //
  // Still ids and enums only — a uuid we issued and a platform name.
  return {
    dealId: owned.id,
    threadId,
    platform,
    brandName,
    replyIntent,
    sendable,
  };
}

// POST /athletes/:id/draft-intent — resolve a brand to a draftable deal.
// No model call. No draft text. No pending action.
router.post(
  "/athletes/:id/draft-intent",
  async (req: Request, res: Response) => {
    res.setHeader("Cache-Control", "no-store");

    const voiceAuth = await voiceAuthorized(req, req.params.id);
    if (!voiceAuth.ok) {
      sendVoiceRefusal(res, voiceAuth);
      return;
    }

    const { id } = req.params;
    if (!UUID_RE.test(id)) {
      res.status(400).json({ error: "Invalid athlete id" });
      return;
    }

    const body = isRecord(req.body) ? req.body : {};

    // ── A dealId TARGETS; a brand RESOLVES ──────────────────────────────────
    // The brand is spoken, so it arrives as a NAME and has to be resolved (by
    // normalized name rather than the thread's brand_id — see ./dealResolver for
    // why that FK is wrong on live data). That resolution is a guess, and on a
    // REVISION there is nothing to guess from: "make it longer" names no brand,
    // so the worker had to re-state one from conversational context. Live it
    // re-stated the wrong one and revised a brand from earlier in the chat
    // instead of the card on screen.
    //
    // So the worker now sends back the dealId it opened. When it does, there is
    // nothing left to resolve: skip straight to the reply path, and let the
    // athlete-scoped re-read below be the only authority on ownership.
    //
    // A malformed id is a 400, NOT a fall-back to `brand`. Falling back would
    // quietly reintroduce the guess this exists to remove, and would do it at
    // exactly the moment something has already gone wrong.
    const hasDealId = body.dealId !== undefined && body.dealId !== null;
    const targetDealId =
      typeof body.dealId === "string" && UUID_RE.test(body.dealId)
        ? body.dealId
        : null;
    if (hasDealId && !targetDealId) {
      res.status(400).json({ error: "Invalid deal id" });
      return;
    }

    // `brand` is only consulted when there is no id to target. A brand sent
    // ALONGSIDE an id is ignored outright — the id is what the athlete is
    // looking at, and a disagreeing brand is precisely the stale value that
    // caused the bug.
    const brand = typeof body.brand === "string" ? body.brand.trim() : "";
    if (!targetDealId && !brand) {
      res.status(400).json({ error: "Missing brand" });
      return;
    }

    const replyIntent = intentOf(body.replyIntent);
    if (!replyIntent) {
      res.status(400).json({ error: "Invalid reply intent" });
      return;
    }

    const conversationId =
      typeof body.conversationId === "string" ? body.conversationId : "";
    if (!UUID_RE.test(conversationId)) {
      res.status(400).json({ error: "Invalid conversation id" });
      return;
    }

    // ── MILA_WELCOME: a draft card is the optional draft_replies capability ──
    // The same check the chat engines make for deals_draft_reply (welcome/toolGate.ts), so voice cannot draft for an
    // athlete who has not turned draft replies on. Before anything is resolved or written; fails closed; transparent
    // while the flag is off (nothing read). Voice has no Turn-on card, so the text never names offer_capability.
    const refusal = await toolRefusal(id, "deals_draft_reply", () => false).catch(() => "deals_draft_reply is off for this athlete: the check failed. Do not retry.");
    if (refusal) {
      logger.info({ athleteId: id, outcome: "capability_off" }, "Draft intent");
      res.status(403).json({ error: "capability_off", message: refusal });
      return;
    }

    try {
      const result = await withTimeout(
        (async (): Promise<DraftIntentResult> => {
          // ── Targeted by id: nothing to resolve ────────────────────────────
          // No brand match, no ambiguity, no duplicate-picking. The card binds
          // to the row the athlete is already looking at, and the athlete-scoped
          // re-read below is what turns someone else's id into a 404.
          //
          // `resolveReplyPath` still runs: whether a reply can actually be SENT
          // is a property of the thread, not of how the deal was found.
          if (targetDealId) {
            return buildCard(
              id,
              targetDealId,
              await resolveReplyPath(id, targetDealId),
              replyIntent,
              conversationId,
            );
          }

          // Athlete-scoped by construction: the resolver only ever reads this
          // athlete's deals. Exact brand match only.
          const resolution = await resolveAthleteDealsByBrand(id, brand);
          if (resolution.outcome !== "match") return null;
          const matches = resolution.deals;
          if (!matches.length) return null;

          // ── Which duplicate? The one that can actually be replied to ────────
          // Duplicate-brand deals are real (see dealResolver — one athlete holds
          // two "Handshake AI" rows), and recency does NOT identify the one
          // carrying the conversation: an athlete's Prime Hydration exists as a
          // threaded Gmail deal AND as a second row with no messages at all.
          //
          // Taking matches[0] bound the card to whichever row sorted first and
          // reported sendable:false for a brand whose thread plainly exists — the
          // wrong answer, arrived at honestly. "Reply to X" means the thread they
          // are actually in, so prefer the first candidate with a real reply path
          // and fall back to the newest when none has one (a brand they have a
          // deal with but no inbox conversation still gets a card, just no Send).
          //
          // Bounded by the number of duplicates for ONE brand — two or three, not
          // a scan — and the extra lookups only happen when the newest row turns
          // out not to be draftable.
          let deal = matches[0];
          let path = await resolveReplyPath(id, deal.dealId);
          if (!(path.threadId && path.hasInbound)) {
            for (const candidate of matches.slice(1)) {
              const p = await resolveReplyPath(id, candidate.dealId);
              if (p.threadId && p.hasInbound) {
                deal = candidate;
                path = p;
                break;
              }
            }
          }

          return buildCard(
            id,
            deal.dealId,
            path,
            replyIntent,
            conversationId,
            brand,
          );
        })(),
        RESOLVE_TIMEOUT_MS,
        "voice draft intent",
      );

      if (!result) {
        // No deal with that brand. The model says so plainly; it does not invent
        // one, and no card is shown.
        logger.info({ athleteId: id, outcome: "no_deal" }, "Draft intent");
        res.status(404).json({ error: "No deal for that brand" });
        return;
      }

      logger.info(
        {
          athleteId: id,
          dealId: result.dealId,
          replyIntent: result.replyIntent,
          sendable: result.sendable,
        },
        "Draft intent resolved",
      );
      res.json(result);
    } catch (err: any) {
      logger.error(
        { athleteId: id, error: err.message },
        "Draft intent failed",
      );
      res.status(500).json({ error: "Internal server error" });
    }
  },
);

export default router;
