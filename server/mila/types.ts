/**
 * types.ts — the Mila tool contract.
 *
 * A MilaTool is a pure server-side function the model can call. The registry
 * maps these to Gemini functionDeclarations; the agent loop validates model
 * args against `argsSchema` before executing.
 */

import { z } from "zod";
import type { ReplyIntent, DraftStyle, DraftVoice } from "../lib/draftPrompt";

export interface MilaTool<Args extends z.ZodTypeAny = z.ZodTypeAny> {
  /** Function name exposed to the model (snake_case). */
  name: string;
  /** Written FOR THE MODEL: what the tool returns and when to call it. */
  description: string;
  /** Zod schema for the model-supplied arguments. Validated before execute. */
  argsSchema: Args;
  /**
   * Optional per-tool execution timeout (ms). The loop wraps `execute` in
   * `withTimeout` at `MILA.TOOL_TIMEOUT_MS` by default; a tool that legitimately
   * runs longer than a read (e.g. `draft_reply`, which calls a model) sets its
   * own ceiling here. Omit for the default.
   */
  timeoutMs?: number;
  /**
   * TENANCY — the most important rule in this file:
   * `athleteId` is ALWAYS the first parameter and is ALWAYS injected
   * server-side from `req.athleteId` by the agent loop. It must NEVER come
   * from model args, and no tool schema may accept an athlete id. Every
   * query inside a tool filters by this id.
   */
  execute(athleteId: string, args: z.infer<Args>): Promise<unknown>;
  /**
   * Optional: what a MODEL is allowed to see of the result (the chat functionResponse, the
   * persisted tool row, the voice wire). The raw result still feeds the in-app widgets.
   * Absent ⇒ the model sees the result as-is. Apply it with `modelViewOf` (./tools/modelView).
   */
  modelView?(result: unknown): unknown;
}

// ─── Widgets ──────────────────────────────────────────────────────────────────
//
// A widget is a small, structured, ALREADY-SAFE view derived from a tool result
// so the client can render a card inline in chat. The wire shape is mirrored on
// the client in `client/hooks/use-mila-chat.ts` (the SSE contract is duplicated
// there the same way the event shape already is).
//
// HARD RULE — a widget NEVER carries raw jsonb, and NEVER carries thread/email
// free text (subjects, summaries, bodies). Those are attacker-controlled and
// stay in the model's prose, not on a card. Widget data is scalar/enum fields
// only. `buildWidget` in `widgets.ts` is the single place that enforces this.
//
// ONE DOCUMENTED EXCEPTION — `reply_action.data.draft` (see below). It is the
// single free-text field any widget may carry, and only because it is the
// athlete's OWN outgoing copy: app-generated by `generateDealDraft`, run through
// the same three strip-guards as the reply endpoint (deterministic
// greeting/signature composed in code + `sanitizeDraftBody` + negotiate
// `lintDraftForLeaks`), and rendered ONLY into an editable text input — never as
// instruction. It is NOT thread/email/brand text and NOT internal scoring/prompt
// data. Nothing else on a card is ever free text.

export type DealCardVerdict = "great" | "good" | "fair" | "poor";
export type DealCardCategory = "PAID" | "MEDIA" | "EDITORIAL" | "GIFTING";

/**
 * deal_card — scalar `deals` columns. No thread/email text, even wrapped.
 * `verdict`/`scoreNumeric` are always NULL: the deal score is gone (inbox_threads.score
 * dropped in 0088). The keys stay for app builds that still read them; the card renders
 * null as an em-dash + "Not scored yet" rather than inventing a midpoint.
 */
export interface DealCardWidgetData {
  id: string;
  brandName: string;
  brandDomain: string | null;
  category: DealCardCategory;
  status: string;
  offerAmount: string | null;
  timeAgo: string;
  verdict: DealCardVerdict | null;
  scoreNumeric: number | null;
}

/**
 * deal_list — an N-deal answer (list_deals) rendered as a vertical stack of the
 * SAME deal_card items above, capped at 5 (order = list_deals order). It carries
 * NOTHING a single deal_card doesn't: each element is a plain DealCardWidgetData
 * (scalars + dealId only, no thread/email text, no threadId/platform). One widget,
 * one message.widget field — the array lives INSIDE, so the wire envelope and the
 * "last widget wins" loop rule are unchanged. When list_deals returned more than
 * these 5, the loop also emits a "See all my deals" nav-chip (see navChips.ts).
 */
export interface DealListWidgetData {
  deals: DealCardWidgetData[];
}

// ─── reply_action ─────────────────────────────────────────────────────────────
//
// The ONLY interactive widget: it renders the reused Draft Reply UI inline so the
// athlete can review, edit, and SEND a brand reply with a deliberate tap. The
// draft is produced server-side (no on-device generation — that streaming path is
// the unfixed native bug); the widget carries the finished, strip-guarded copy as
// DATA. It carries NO pendingActionId — the send is PROPOSE-AT-TAP (the client
// creates a send_reply pending action with the CURRENT edited body, then approves
// it), so an old widget in scrollback can only ever act on its own thread.

/** Params Mila drafted with — seed the (display-only) sheet controls. */
export interface ReplyActionParams {
  replyIntent: ReplyIntent;
  style: DraftStyle;
  voice: DraftVoice;
  selectedTerms: string[]; // athlete-authored negotiate asks (bounded), not email text
  includeMediaKit: boolean;
}

export interface ReplyActionWidgetData {
  dealId: string;
  /** The thread to reply into. null → nothing to reply to → not sendable. */
  threadId: string | null;
  /** `lastInbound.platform ?? "gmail"` — the SAME expression the send route uses. */
  platform: string;
  /** gmail|instagram AND a thread AND no refusal. UX gate only — the server
   *  re-derives platform + re-checks tenancy/at-most-once authoritatively at send. */
  sendable: boolean;
  brandName: string;
  /** THE single allowed free-text field (see the carve-out above). null on refusal. */
  draft: string | null;
  /** Fixed app string when the leak-lint couldn't produce clean copy → no-Send state. */
  refusal: string | null;
  /**
   * The card exists but its body does not yet — the CLIENT must generate it via
   * the normal /deals/:id/draft path before there is anything to review.
   *
   * Only ever set by the voice flow (server/voice/draftIntentRoute.ts), which
   * deliberately does not draft: a draft is derived from the brand's own email,
   * and generating it there would carry that prose back through the worker, a
   * live model's context, and a data channel. Absent on the text path, where
   * `draft` is already populated.
   *
   * EXPLICIT rather than inferred from `draft === null`: making a MISSING field
   * mean "run a model generation" would let an omission trigger spend, and this
   * card is now reachable from a channel whose payloads are untrusted.
   */
  needsDraft?: boolean;
  params: ReplyActionParams;
}

// ─── onboarding_update ────────────────────────────────────────────────────────
//
// The first-entry receipt card (PR 3): what complete_onboarding_step just saved, and — after
// the greeting — the two doors. `saved[].value` is the SECOND documented free-text carve-out
// after reply_action.draft, on the same grounds: it is the ATHLETE'S OWN words about
// themself, validated against a fixed field vocabulary and length-capped server-side
// (server/mila/onboarding.ts), and rendered only as a receipt line. It is never research,
// email, or model prose. Every other field is an enum or an id.

export interface OnboardingSavedFact {
  field: string;
  label: string;
  value: string;
  /** The profile_write receipt; the card's Undo posts to /agent-actions/:id/undo. */
  agentActionId: string | null;
}

export interface OnboardingUpdateWidgetData {
  runId: string;
  step: "greet" | "doors";
  saved: OnboardingSavedFact[];
  /** "doors" → render the two door buttons; "done" → onboarding is finished, the client may close. */
  next: "doors" | "done";
  door: "profile" | "deals" | null;
}

