/**
 * studio/agent/cast — which of HER photographs each planned item is made from.
 *
 * The planner returns a search QUERY per item, never an asset (studio/agent/types.ts `PlanItem`):
 * a model naming an asset is the thing tenancy says never to trust. This module resolves each query
 * against her own library, server-side, and decides.
 *
 * ─── ⚠️  searchMedia IS THE SEARCH, NOT THE JUDGE ──────────────────────────────────────────────
 *
 * `searchMedia` (services/mediaSearch.ts) is shared and is not changed here. Three things about it
 * decide how its answer may be used, all read from the code:
 *
 *   1. It filters on athlete, stored and top-level — and NOT on media_type or deleted_at. A video
 *      with a poster comes back looking like a still, and a soft-deleted row comes back at all.
 *   2. Every tag filter guards on `x.tags &&`, so a row with NO tags passes all of them, scores
 *      exactly zero and is returned as filler whenever the shelf is thin
 *      (docs/studio-agent-open-cards.md card 1).
 *   3. `athletePresent` is truthy-only: `false` is a no-op, and an untagged row passes `true` too.
 *
 * So every candidate it returns is RE-LOADED through one athlete-scoped predicate of our own —
 * hers, stored, not deleted, top-level, a photograph — and judged on its vision tags here:
 *
 *   i2v     `athlete_present === true`  — an identity shot, Veo; nothing unknown goes in — AND
 *           the row is hers by provenance: her camera or synced from her accounts, or a photo she
 *           PICKED herself. A "made here" still is never an i2v ref on the tagger's word alone.
 *
 * The equality IS the untagged guard: a row with no tags has no `athlete_present`, so it is not
 * `true`. Loosening i2v to "not known to be absent" (`!== false`) is what trusting searchMedia's
 * filter would amount to, and it casts a row nothing has established she is in.
 *
 * ─── S1 — A MADE-HERE STILL IS NEVER AN i2v REF UNLESS SHE PICKED IT (22 Sep 2026) ──────────────
 *
 * The lookalike gap fired on day one of plans animating refs: a live plan cast a generated still
 * (a6a8b954 — "a female soccer player smiles joyfully… teammates frame the foreground") as an i2v
 * of her, and it is visually not her (owner-confirmed). It passes `athlete_present` (the tagger
 * was asked "is the athlete in frame" and a generated female athlete IS one) and the subject guard
 * (unnamed, person-worded). No text signal exists: the model cannot tell a lookalike. What the
 * row DOES say is where it came from — `origin = 'generated'` — and on the measured library 267
 * of 360 made-here stills of "her" were generated by a job that carried NO reference of her, so
 * the face is whoever the model drew. An i2v puts a face in motion under her name; that is the
 * one cast a tagger's word may not authorise. Her camera and her synced accounts are hers by
 * construction; a photo she picked is her own decision. Everything else is `image` (held, never
 * animated) or swapped to a photo that is hers. S2 (a made-here still whose job carried her
 * reference pack) refines this by reading the job — its own commit.
 *
 * ⚠️ MUTATION (cast.test S1): drop the provenance clause — "a made-here still named as an i2v ref
 * is swapped to her camera photo" reds by name; so does the route's teammates fixture.
 *
 * ─── S2 — A MADE-HERE STILL WHOSE JOB CARRIED HER REFERENCE IS HERS BY CONSTRUCTION ────────────
 *
 * S1's cost: the 93 made-here stills on the measured library that WERE generated from a reference
 * of her (a `person` reference on the job — studio/brief.ts `JobReference`) lost i2v with the 267
 * that were not. The one fact that says a generated face was hers is on the job row, so the
 * predicate reads it: a LEFT JOIN to `generation_jobs` on `generation_job_id`, WITH the athlete on
 * the join (content.ts's fail-safe — `generation_job_id` is a bare uuid with no FK on this side,
 * so an asset pointing at someone else's job must miss the join and read as unbound rather than
 * borrow their pack). `identityBound` is true when that job's frozen brief holds a person
 * reference, false when the job is hers and holds none, null when no job of hers is found (an
 * upload, a stitched compilation, a foreign job). Only `true` opens i2v. Read-only; no new index
 * (the join is the primary key); the table is Studio's own (studio/jobs.ts is its only writer).
 *
 * ⚠️ MUTATIONS (cast.test S2): drop the identity-bound arm — "a made-here still whose job carried
 * her reference fits i2v unpicked" reds by name; drop the athlete from the join — "a job that is
 * not hers binds nothing" reds by name.
 *
 * ─── S1b — ON AN OWN-FOOTAGE BRIEF, A MADE-HERE STILL IS REFUSED IN EVERY MOTION ────────────────
 *
 * The round-2 re-run (22 Sep 2026) put a made-here still, pushed in, into "a recap of this week's
 * training, using what I actually filmed": S1 gated i2v and nothing wider, and a held or
 * pushed-in image is the same generated face on a brief that asked for what she filmed. So when
 * her sentence asks for her own footage (studio/agent/footageAsk.ts — the same reading the
 * planner is told), every photo kind — i2v ref, held still, pushed-in still — takes S1's gate:
 * her camera, her accounts, or a photo she picked. The identity-bound arm (S2) does not apply
 * there: a still generated FROM her is still not something she filmed. Off an own-footage brief
 * nothing changes.
 *
 * ⚠️ MUTATION (cast.test S1b, studio.agent.test): exempt held stills — "a made-here still named as
 * an image item on an own-footage brief is swapped to her camera photo" reds by name.
 *
 * ─── B-ROLL IS NOT CAST AT ALL (21 Sep 2026) ──────────────────────────────────────────────────
 *
 * B-roll is made from WORDS (docs/studio-broll-t2v-decision.md): the planner names no photo for it,
 * and this module searches for none, gates none on `athlete_present`, and swaps none. A b-roll item
 * comes back with no photo and NOT left out — the Board makes it from its direction alone, on the
 * photo-less path it already has. Products are not b-roll: a product keeps HER photo and stays
 * image-to-video, because her actual product has to appear, not one a model imagined.
 *
 * ─── WHAT HAPPENS TO AN ITEM NOTHING FITS ───────────────────────────────────────────────────────
 *
 * It is DROPPED AND SHOWN (decided 21 Sep 2026): the plan she is shown carries a line where the item
 * was, and she approves what she sees. The whole plan is refused only when NOTHING in it can be made
 * — no item with a photo, and no b-roll made from words.
 *
 * ─── WHERE EACH KIND IS LOOKED FOR ──────────────────────────────────────────────────────────────
 *
 *   i2v     `searchMedia`, whose ranking favours hero shots of her — which is what an identity shot
 *           wants.
 *   broll   nowhere. See above.
 *
 * `rankWithoutHer` stays: the ROUTE uses it to show the planner her scenes as context (studio.ts
 * POST /studio/agent/plan), because a scene she has is evidence of where she plays — something a
 * sentence-made b-roll shot can stay true to. It casts nothing.
 *
 * ─── COST ───────────────────────────────────────────────────────────────────────────────────────
 *
 * One `embedText` per i2v item whose named photo could not be used — at most MAX_PLAN_ITEMS. No
 * generation, no preview, no spend.
 */
