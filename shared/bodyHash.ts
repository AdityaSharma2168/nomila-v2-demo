/**
 * bodyHash.ts — the ONE hash of an outbound reply body, shared by client and server.
 *
 * Approve carries `body_sha256`: the client hashes the body it DISPLAYED, the server
 * re-hashes `payload.body` as stored, and a mismatch is refused (409) — so what the
 * athlete approved is byte-for-byte what sends. Both sides import THIS function so they
 * cannot drift.
 *
 * Rules: SHA-256 over the UTF-8 bytes of the string exactly as given, lowercase hex.
 * No trimming, no Unicode normalisation, no newline folding — the payload already stores
 * the body as it will send, and that string is what gets hashed. A lone surrogate encodes
 * as U+FFFD (EF BF BD), matching TextEncoder and Node's Buffer.
 *
 * Dependency-free on purpose: it runs under Hermes (no node:crypto, and expo-crypto is
 * async and native) and under Node, and must give the same answer in both.
 */

