/**
 * agent/engine/mastra/ddl.ts — the Mastra engine's tables as OUR migration (0147): @mastra/pg exportSchemas for the
 * "mastra" schema, normalised (trailing spaces and blank runs removed), under a fixed header. Used by
 * scripts/mastra/exportDdl.ts (write / --check) and mastraStore.migration.test.ts (the file must equal this: it is
 * what a FRESH install creates). Then our own three columns on mila_tf_sessions (OUR_COLUMNS_SQL).
 *
 * Rule for a @mastra/pg bump: 0147 is applied already and IF NOT EXISTS never alters an existing table, so a version
 * whose DDL differs needs a NEW numbered migration with the ALTER statements (and the test's pinned version moved);
 * never regenerate or edit 0147. The test fails on a bump until that is done.
 */
import { readFileSync } from "node:fs";
import { join } from "node:path";

export const MASTRA_MIGRATION_FILE = "0147_mastra_engine.sql";
export const MASTRA_SCHEMA = "mastra";

function pgVersion(): string {
  return (JSON.parse(readFileSync(join(require.resolve("@mastra/pg"), "..", "..", "package.json"), "utf8")) as { version: string }).version;
}

/**
 * Our own columns, hand-written (not from @mastra/pg), after Mastra's tables: on mila_tf_sessions (public), the turn
 * running on a conversation (one at a time, across instances) and the engine that ran its last turn (an engine change
 * starts the conversation over on the new engine). Nullable, no default, IF NOT EXISTS: re-runs are no-ops and no row
 * is rewritten.
 */
export const OUR_COLUMNS_SQL = [
  `-- Our own columns (hand-written, not from @mastra/pg): one Mastra turn at a time per conversation, and the engine`,
  `-- that ran its last turn (server/agent/tf/sessions.ts).`,
  `ALTER TABLE "mila_tf_sessions" ADD COLUMN IF NOT EXISTS "running_run_id" uuid;`,
  `ALTER TABLE "mila_tf_sessions" ADD COLUMN IF NOT EXISTS "running_at" timestamp with time zone;`,
  `ALTER TABLE "mila_tf_sessions" ADD COLUMN IF NOT EXISTS "last_engine" text;`,
].join("\n");

/** Mastra's own DDL as @mastra/pg exports it for the "mastra" schema, normalised. What a FRESH install creates. */
export function mastraExportSql(): string {
  // eslint-disable-next-line @typescript-eslint/no-require-imports
  const { exportSchemas } = require("@mastra/pg") as { exportSchemas(schema: string): string };
  return exportSchemas(MASTRA_SCHEMA)
    .split(/\r?\n/).map((l) => l.trimEnd()).join("\n")
    .replace(/\n{3,}/g, "\n\n").trim();
}

/** The @mastra/pg version 0147 was generated from. A different installed version needs a NEW migration (ALTERs). */
export const MASTRA_PG_VERSION_0147 = "1.32.0";

export function mastraMigrationSql(): string {
  const body = mastraExportSql();
  const head = [
    `-- 0147_mastra_engine.sql — the Mastra engine's own tables (MILA_ENGINE=mastra; server/agent/engine/mastra).`,
    `-- Generated by scripts/mastra/exportDdl.ts from @mastra/pg ${pgVersion()} exportSchemas("${MASTRA_SCHEMA}"); do not edit by hand.`,
    `-- Its OWN schema: no table in public is created; the only public change is three nullable columns of ours on`,
    `-- mila_tf_sessions, at the end. Every statement is IF NOT EXISTS (re-runs are no-ops); no transaction control. The`,
    `-- store runs with disableInit, so these tables are never created or altered at runtime. IF NOT EXISTS never alters`,
    `-- an existing table: a @mastra/pg bump that changes this DDL needs a NEW migration with the ALTERs, never an edit here.`,
    `-- Rows are an athlete's Mila threads and messages: account deletion purges them (engine/mastra/lifecycle.ts).`,
    `--`,
    `-- The POC's dev-only schema "mastra_poc" (PR #1157, 53 empty tables, never on prod) is dropped here; IF EXISTS makes`,
    `-- it a no-op everywhere else.`,
    `DROP SCHEMA IF EXISTS "mastra_poc" CASCADE;`,
  ].join("\n");
  return `${head}\n\n${body}\n\n${OUR_COLUMNS_SQL}\n`;
}
