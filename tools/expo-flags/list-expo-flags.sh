#!/usr/bin/env bash
# list-expo-flags.sh — every EXPO_PUBLIC_* name the client reads, derived from the code (PR 4, C2).
#
# EXPO_PUBLIC_* is inlined into the bundle at BUILD time, so a flag the client reads but the build
# never sets is off, silently. This lists what the client actually reads, so a build script — local
# or a workflow — can be checked against the code rather than against memory.
#
#   bash tools/expo-flags/list-expo-flags.sh             # names, one per line, with the file reading each
#   bash tools/expo-flags/list-expo-flags.sh --names     # names only
#   bash tools/expo-flags/list-expo-flags.sh --script    # an expo-dev.sh that turns every STUDIO_* on
#
# Only the dot form (process.env.EXPO_PUBLIC_X) is found — it is also the only form Expo inlines.
# Read-only: greps client/, writes nothing. Values are never printed; this knows names, not .env.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "${ROOT}"

names() {
  grep -rhoE 'process\.env\.EXPO_PUBLIC_[A-Z0-9_]+' client --include='*.ts' --include='*.tsx' \
    | sed 's/^process\.env\.//' | sort -u
}

case "${1:-}" in
  --names)
    names
    ;;
  --script)
    studio="$(names | grep '^EXPO_PUBLIC_STUDIO_' | sed 's/$/=true/' | tr '\n' ' ')"
    cat <<SCRIPT
#!/bin/bash
# expo-dev.sh — generated by tools/expo-flags/list-expo-flags.sh --script. Do not hand-edit: re-run it.
# Every EXPO_PUBLIC_STUDIO_* flag the client reads, on. Everything else (EXPO_PUBLIC_API_URL, …) comes
# from the checkout's .env, as expo loads it. Port 8083 exactly: Metro silently jumps to 8082 (CORS-blocked)
# when 8081 is busy. Usage: expo-dev.sh [dir]
cd "\${1:-.}" && ${studio}npx expo start -c --port 8083
SCRIPT
    ;;
  "")
    for n in $(names); do
      printf '%-36s %s\n' "${n}" "$(grep -rlE "process\.env\.${n}\b" client --include='*.ts' --include='*.tsx' | head -1)"
    done
    ;;
  *)
    echo "usage: $0 [--names | --script]" >&2
    exit 2
    ;;
esac
