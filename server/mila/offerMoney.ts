/**
 * offerMoney.ts — the speakable offer figure, resolved from structured fields only.
 *
 * Pure: no db, no model, no clock. Same discipline as ../lib/dealVoice, whose
 * money-safety rules this module implements for the voice wire.
 *
 * ── The bug this exists to close ─────────────────────────────────────────────
 * The voice wire spoke `deals.amount`. That column is a DENORMALIZED SNAPSHOT
 * written once at detection from the classifier's read of the first email
 * (server/skills/dealDetector.ts, `upsertDealForThread`). It does not track the
 * negotiation. `../lib/dealVoice` states the rule at its head, with the observed
 * failure: "NEVER speak `deals.amount`. It goes stale (we saw $200 on a deal
 * whose live offer was $950)." Its own resolver structurally cannot see the
 * column. The voice route read exactly that column and read it aloud.
 *
 * The live figure lives on the thread, in `conversation_state.key_details`,
 * regenerated by the summarizer on every new message.
 *
 * ── Why this is not just a call to resolveSpokenAmount ───────────────────────
 * `resolveSpokenAmount` returns a FORMATTED STRING and its last fallback is
 * `conversation_state.offer_display` — a model-written line ("$75/creative · 15%
 * commission · free device"). That is correct for a screen and wrong here: this
 * result reaches a TTS layer that reads free text aloud verbatim, which is the
 * boundary ./dealRoutes exists to hold. So this module resolves to NUMBERS and a
 * closed unit enum, and no prose field is reachable from it at all.
 *
 * `detectAmountConflict` IS reused rather than restated — it is pure, already
 * tested, and the 15% threshold must not drift between the screen and the call.
 *
 * ── FOUR states, because "no figure" means two different things ───────────────
 * The interesting decision here. Collapsing the no-structured-figure case into
 * one answer produces a false statement half the time:
 *
 *   stated     — a structured figure. Speak it.
 *   range      — several distinct figures stated. Speak the span, not a point.
 *   unverified — the deal row carries a detected figure but the thread has no
 *                structured backing for it. A number WAS named; we just cannot
 *                stand behind our stored copy. Saying "they haven't named a
 *                number" here is FALSE, and speaking the stale one is the bug.
 *                So: no figure crosses, and the state says why.
 *   unstated   — no figure anywhere, on the row or in the thread. Nobody has
 *                named a price. This one is safe to say out loud.
 *
 * `unverified` is the state that keeps this fix honest in both directions. It
 * needs to know only WHETHER the deal row had an amount, never its value — so
 * the caller passes a boolean and the column itself never enters this module.
 *
 * Related but NOT the same thing: `score.economicsState.state`
 * (priced|unpriced|tbd) describes what the SCORER could assess at scoring time.
 * This describes which figure is safe to say NOW. A deal can be `priced` and
 * `unverified` at once — that is precisely the stale case.
 */

// Lives under mila/ rather than voice/ deliberately: `voice/` already imports
// `mila/tools/*` (dealBriefRoute → getDeal), so putting this the other side of
// that edge would close an import cycle. Both consumers reach it from here.
import {
  detectAmountConflict,
  type ConversationState,
} from "../lib/dealVoice";
import { matchRate } from "../skills/dealScoreGrid";
import {
  deriveDeliverables,
  readDeliverables,
  type DeliverableCounts,
} from "./deliverables";

/**
 * Which figure, if any, is safe to speak. See the header — `unverified` and
 * `unstated` are deliberately distinct.
 */
export type MoneyState = "stated" | "range" | "unverified" | "unstated";

/**
 * What the amount buys. Closed vocabulary, exactly as the summarizer is
 * instructed to emit it (server/skills/threadSummarizer.ts). Validated against
 * this set on the way out, so a drifted or model-invented unit becomes null
 * rather than a word read aloud.
 */
export const OFFER_UNITS = [
  "per_post",
  "per_deliverable",
  "total",
  "monthly",
  "annual",
  "per_appearance",
  "commission_only",
  "gifting_only",
] as const;
export type OfferUnit = (typeof OFFER_UNITS)[number];

const UNIT_SET: ReadonlySet<string> = new Set(OFFER_UNITS);

/**
 * Sanity ceiling on a spoken figure. A real NIL offer is far below this; a value
 * above it means the jsonb is wrong, and an absurd number read aloud is worse
 * than no number. Reject-don't-coerce, same as the 1–10 grid bound in
 * ./dealRoutes.
 */
const MAX_OFFER = 100_000_000;

/** The speakable offer. Numbers and closed enums only — no string is derived from prose. */
export interface VoiceOffer {
  /** The single speakable figure, or null on `range`/`unverified`/`unstated`. */
  amount: number | null;
  /** Range bounds. Both null unless `moneyState === "range"`. */
  low: number | null;
  high: number | null;
  unit: OfferUnit | null;
  recurring: boolean | null;
  commissionPct: number | null;
  /**
   * What the deal actually asks for — "two reels and three stories" instead of
   * the `deal_type` enum, which maps EVERY paid deal to the string
   * "social_post" (server/skills/dealDetector.ts, `categoryToDealType`). That
   * one coarse mapping is the whole of why Mila defaults to "a social post".
   *
   * Allow-listed keys, integer counts. `null` — never `{}` — when nothing
   * survived, so "no deliverables recorded" is one check rather than two.
   */
  deliverables: DeliverableCounts | null;
  moneyState: MoneyState;
  /**
   * The structured figure disagrees with the deal row's detected one by more
   * than 15% — i.e. the number MOVED since detection. Lets the worker say "they
   * came up to twelve hundred" instead of asserting a figure with no history.
   * False whenever there is nothing to compare.
   */
  moved: boolean;
}

const EMPTY: VoiceOffer = {
  amount: null,
  low: null,
  high: null,
  unit: null,
  recurring: null,
  commissionPct: null,
  deliverables: null,
  moneyState: "unstated",
  moved: false,
};

/** A finite, positive, plausibly-real money figure — or null. */
function money(v: unknown): number | null {
  if (typeof v !== "number" || !Number.isFinite(v)) return null;
  if (v <= 0 || v > MAX_OFFER) return null;
  return v;
}

const isRecord = (v: unknown): v is Record<string, unknown> =>
  v !== null && typeof v === "object" && !Array.isArray(v);

/**
 * The speakable offer for one deal.
 *
 * `hasDetectedAmount` is whether `deals.amount` held a figure — a BOOLEAN, never
 * the value. It only ever selects between `unverified` and `unstated`; it can
 * never become something spoken. Passing the number instead would put the stale
 * column one careless line away from the wire again.
 */
export function resolveVoiceOffer(
  conversationState: unknown,
  hasDetectedAmount: boolean,
  detectedAmount?: number | null,
  rawDeliverables?: unknown,
): VoiceOffer {
  const cs = (
    isRecord(conversationState) ? conversationState : null
  ) as ConversationState | null;
  const kd = cs?.key_details ?? null;
  const os = kd?.offer_struct ?? null;

  // Terms travel with the figure but do not gate it: a stated commission with no
  // cash number is still worth knowing, and `gifting_only` carries no amount by
  // definition.
  const unit =
    typeof os?.unit === "string" && UNIT_SET.has(os.unit)
      ? (os.unit as OfferUnit)
      : null;
  const recurring = typeof os?.recurring === "boolean" ? os.recurring : null;
  const rawPct = os?.commission_pct;
  const commissionPct =
    typeof rawPct === "number" &&
    Number.isFinite(rawPct) &&
    rawPct > 0 &&
    rawPct <= 100
      ? rawPct
      : null;

  // ── Deliverables: structured first, derived only to fill a gap ─────────────
  // Deliverables sit with the terms, not with the figure: a deal can say what it
  // wants without saying what it pays (`economicsState: "tbd"` is exactly that
  // shape), and that is the case where naming the scope matters most.
  //
  // PRECEDENCE IS ABSOLUTE. `offer_struct.deliverable_counts` is the summarizer's
  // own structured read and wins outright; `deriveDeliverables` only runs when
  // that came back null, i.e. for the text-only deals that would otherwise give
  // voice nothing. A derived count never merges with, tops up, or overrides a
  // structured one — mixing a parsed number into an authoritative object would
  // make the result impossible to reason about.
  const structured = readDeliverables(os?.deliverable_counts);
  const derived = structured ? null : deriveDeliverables(rawDeliverables);

  const terms = {
    unit,
    commissionPct,
    deliverables: structured ?? derived?.counts ?? null,
    // The stored flag still wins. The derived one only speaks up where the
    // summarizer never ran, and it exists so "one post per week" is not read as
    // a one-off — see ./deliverables on why the count stays literal.
    recurring: recurring ?? (derived ? derived.recurring : null),
  };

  // ── 1. The structured figure wins. ────────────────────────────────────────
  const structAmount = money(os?.amount);
  if (structAmount !== null) {
    return {
      ...EMPTY,
      ...terms,
      amount: structAmount,
      moneyState: "stated",
      // Only meaningful against a structured base, which is what
      // detectAmountConflict requires. Reused, not restated — the 15% threshold
      // must not drift from the screen's.
      moved: detectAmountConflict(
        { amount: detectedAmount ?? null },
        { conversation_state: cs ?? undefined },
      ),
    };
  }

  // ── 2. The stated figures, in order. ──────────────────────────────────────
  const amounts = Array.isArray(kd?.amounts)
    ? kd.amounts.map(money).filter((n): n is number => n !== null)
    : [];

  if (amounts.length > 0) {
    const lo = Math.min(...amounts);
    const hi = Math.max(...amounts);
    // Several figures that agree are one figure, not a range.
    if (lo === hi) {
      return { ...EMPTY, ...terms, amount: lo, moneyState: "stated" };
    }
    return { ...EMPTY, ...terms, low: lo, high: hi, moneyState: "range" };
  }

  // ── 3. Nothing structured. Which silence is it? ───────────────────────────
  // `unverified` when the row held a figure we cannot corroborate — a number was
  // named, so denying one exists would be false. `unstated` when there is none
  // anywhere, which is a true and useful thing to say.
  return {
    ...EMPTY,
    ...terms,
    moneyState: hasDetectedAmount ? "unverified" : "unstated",
  };
}

