/**
 * library.ts — the free music library: tracks from licence-checked free sources, each tagged for the finder
 * (find.ts) and each with its own paper trail.
 *
 * ─── WHERE EVERYTHING IS ────────────────────────────────────────────────────────────────────────
 *
 *   library.manifest.json   one row per track: what it is (title, artist, tags), where it came from (track page, the
 *                           licence the page showed, the day), the exact bytes (SHA-256 of the download and of the
 *                           uploaded file, the MD5 the bucket reported) and its measured loudness. Generated by
 *                           scripts/music/build_manifest.py from the downloads; edited by hand only to correct a tag.
 *   LIBRARY-LICENSES.md     the same licence facts in prose, one block per track, with the page's own words.
 *   the bucket              studio/tracks/free/<id>.m4a in the media bucket — the tracks.ts pattern. The bytes are not
 *                           in the repo.
 *
 * A committed file, not a table, for the reason tracks.ts and beds.ts give: product media, the same for every athlete,
 * changed in a reviewed diff.
 *
 * ─── THE RULES A ROW IS HELD TO (library.test.ts) ───────────────────────────────────────────────
 *
 *  - Licence is CC0-1.0, CC-BY-4.0 or CC-BY-SA-4.0 — nothing NC, ND, "personal use" or a site's own terms.
 *  - A CC-BY / CC-BY-SA row carries a TASL credit line; a kit that uses it carries that line in the caption, locked.
 *  - brandSafe is true ONLY for CC0 with no third-party sample risk (brandSafeWhy says which). An attribution licence
 *    is never brand-safe here: the credit would have to travel with a brand's deliverable, which the brand controls —
 *    the same reason BEDS-LICENSES.md keeps CC-BY out of the beds.
 *  - Loudness: −14 LUFS integrated (±0.5) under −1 dBTP true peak (taxonomy.ts, finishing.ts).
 *  - Nobody has listened to these start to finish yet (`listenedBy: null`). They are offered only behind
 *    AGENT_POST_KIT_MUSIC_CHOICES, a dev flag, so a person hears them in the app before anything goes further.
 */
import { z } from "zod";
import { studioGovernanceFlag } from "../studioFlag";
import manifest from "./library.manifest.json";
import { TRACK_GENRES, TRACK_MOODS, TRACK_THEMES, TRACK_VOCALS } from "./taxonomy";

export const LIBRARY_LICENCES = ["CC0-1.0", "CC-BY-4.0", "CC-BY-SA-4.0"] as const;
export type LibraryLicence = (typeof LIBRARY_LICENCES)[number];
export const LIBRARY_SOURCES = ["incompetech", "fma-holiznacc0"] as const;

/** Bucket prefix for the library's files. */
export const LIBRARY_PREFIX = "studio/tracks/free/";

const hex64 = z.string().regex(/^[0-9a-f]{64}$/);
const https = z.string().regex(/^https:\/\/\S+$/);

export const libraryTrackSchema = z
  .object({
    id: z.string().regex(/^[a-z0-9]+(-[a-z0-9]+)*$/),
    title: z.string().min(1),
    artist: z.string().min(1),
    source: z.enum(LIBRARY_SOURCES),
    /** The track's own page (or, for a catalogue site, the catalogue page that renders its licence block). */
    sourceUrl: https,
    /** The file as the page links it. */
    fileUrl: https,
    retrievedOn: z.string().regex(/^\d{4}-\d{2}-\d{2}$/),
    licence: z.enum(LIBRARY_LICENCES),
    /** What the page said, verbatim. */
    licenceShown: z.string().min(1),
    /** True for CC-BY / CC-BY-SA: the post must carry `creditLine`. */
    attributionRequired: z.boolean(),
    /**
     * The credit, TASL (Title, Author, Source, Licence — creativecommons.org's recommended practice), as the caption
     * carries it, locked: a caption edit that drops it gets it back (agent/postKit/edit.ts). Null when none is owed.
     */
    creditLine: z.string().min(1).nullable(),
    /** The text the source itself asks for, verbatim (Incompetech's "Attribution Code"); null when none. */
    sourceCreditText: z.string().min(1).nullable(),
    /**
     * Whether the recording is registered with YouTube Content ID: true when the source says claims are made on it,
     * false when it says not, null when it says nothing. Incompetech pre-registers every recording on purpose (its
     * youtube-contentid.html page): a YouTube upload can be claimed, and the claim is released on dispute once the
     * credit is in the description. The stored provenance is the evidence for that dispute.
     */
    contentIdRegistered: z.boolean().nullable(),
    brandSafe: z.boolean(),
    /** One plain sentence: why it is or is not brand-safe. */
    brandSafeWhy: z.string().min(1),
    /** 1–2, from the mood enum, strongest first. */
    moods: z.array(z.enum(TRACK_MOODS)).min(1).max(2),
    /** Where the moods came from: the source's own feel tags, or our reading of album and title. */
    moodsFrom: z.string().min(1),
    /** The recording's ISRC, when the source publishes one. */
    isrc: z.string().regex(/^[A-Z]{2}[A-Z0-9]{3}\d{7}$/).optional(),
    /** 1–5, measured (onset strength and rate, tempo, brightness, in quintiles of this library), kept consistent with the mood. */
    energy: z.number().int().min(1).max(5),
    genre: z.enum(TRACK_GENRES),
    themes: z.array(z.enum(TRACK_THEMES)).max(5),
    /** Null until someone has listened (vocals are not detected by code). */
    vocals: z.enum(TRACK_VOCALS).nullable(),
    bpm: z.number().min(40).max(220),
    /** "stated": the author's figure (the detector agreed, or found its double/half); "measured": ours only. */
    bpmSource: z.enum(["stated", "measured"]),
    /**
     * Seconds to beat 0, in [0, 60/bpm) — measured with librosa's beat tracker on the normalised file, kept only when
     * the track's two halves agree (≤ 0.5 BPM, ≤ 30 ms of phase); null otherwise. Not ear-checked, unlike tracks.ts.
     */
    firstBeatSec: z.number().min(0).nullable(),
    /** Where a cut can land: the drop (the biggest 2 s rise in level, ≥ 6 dB; null when there is none) and the loudest 8 s. */
    sections: z.object({ dropSec: z.number().min(0).nullable(), peakSec: z.number().min(0) }).strict(),
    durationSec: z.number().positive(),
    /** Starts and ends at full level (no fade-in, no fade-out, no silent tail): it can restart under a long cut. */
    loops: z.boolean(),
    gcsPath: z.string(),
    bytes: z.number().int().positive(),
    sha256: hex64,
    md5Base64: z.string().regex(/^[A-Za-z0-9+/]{22}==$/),
    sourceFile: z.string().min(1),
    sourceSha256: hex64,
    loudness: z.object({ integratedLufs: z.number(), truePeakDbtp: z.number(), method: z.string().min(1) }).strict(),
    /** Who listened start to finish, and when — null until someone has. */
    listenedBy: z.string().nullable(),
  })
  .strict();
export type LibraryTrack = z.infer<typeof libraryTrackSchema>;

/** Parsed once at load: a malformed row fails the import loudly rather than offering a half-described track. */
export const LIBRARY_TRACKS: Readonly<Record<string, LibraryTrack>> = Object.freeze(
  Object.fromEntries(z.array(libraryTrackSchema).parse(manifest).map((t) => [t.id, t])),
);

export const isLibraryTrackId = (v: unknown): v is string =>
  typeof v === "string" && Object.prototype.hasOwnProperty.call(LIBRARY_TRACKS, v);

/**
 * STUDIO_MUSIC_LIBRARY_READY — the free library's files are installed in THIS environment's media bucket at
 * studio/tracks/free/<id>.m4a, each matching its manifest MD5 (scripts/music/verify_bucket.py). Its own gate, not
 * STUDIO_STITCH_BEDS_READY: that one covers the beds and the Artlist tracks, and a flip of it must never start offering
 * 83 files nobody copied. Off unless exactly "true": no library track is suggested, signed or rendered.
 */
export function musicLibraryReady(): boolean {
  // Strict, never under STUDIO_ALL_ON: the master must not claim 83 files are in a bucket nobody verified.
  return studioGovernanceFlag(process.env.STUDIO_MUSIC_LIBRARY_READY);
}
