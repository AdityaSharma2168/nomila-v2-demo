// ─── Nav-chips ──────────────────────────────────────────────────────────────
//
// A nav-chip is a READ-ONLY navigation shortcut the client renders under an
// answer: "Open this deal", "See your score". It navigates to an existing app
// screen and NOTHING more — no draft, no reply, no send. Anything that would
// mutate or leave the app is out of scope here (that's PR-7); a "reply"-shaped
// follow-up is an ask-chip (a prefilled question), never a nav-chip.
//
// The target is SEMANTIC, not a React-Navigation route: the server says "score"
// or "deal", the client maps that to the actual screen (score lives on the Brand
// tab, a deal opens as its Thread). This keeps the server free of RN route names.
//
// GROUNDING + TENANCY: nav-chips are derived deterministically in `navChips.ts`
// from the tools the model actually called THIS turn and their results, so a chip
// only ever points at what the answer was about. Any id it carries (a threadId)
// came from a tool that already scoped to the athlete server-side, and the
// destination screen re-fetches scoped too — so a nav-chip can't cross tenancy.

// Every navigable destination is SCREEN-LEVEL (a tab / list home) except `deal`,
// which carries a tenancy-scoped threadId (get_deal's job). `signals`, `pitches`,
// and `media` are deeper stack screens now wired end-to-end (see handleNavigate in
// client MainTabNavigator.tsx). Detail screens PitchDetail/MediaDetail are NOT
// by-id-navigable yet — the navigate tool routes those requests to their list
// (`pitches` / `media`); by-id nav is a follow-up (needs model-side id resolution).

/** The screen-level targets (no id param) the navigate tool may emit. */
export type NavScreen =
  | "deals"
  | "score"
  | "signals"
  | "profile"
  | "studio"
  | "pitches"
  | "media"
  // PR B — the Brand tab's own screens (Deck, Rates) and tabs (Facts, Story).
  | "deck"
  | "rates"
  | "facts"
  | "story";

export type MilaNavTarget =
  | { screen: "deal"; threadId: string; brandName?: string }
  // Checkpoint 1: open the EXISTING upload surface for one of her requests. She does the upload; the chip only opens it.
  | { screen: "add_contract"; requestId: string }
  | { screen: "add_document"; requestId: string }
  | { screen: NavScreen };

export interface MilaNavChip {
  /** Short button label, e.g. "Open this deal". */
  label: string;
  target: MilaNavTarget;
}
