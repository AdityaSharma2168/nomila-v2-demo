/**
 * Cast a plan. Never throws for an item that does not fit — that item is dropped and shown.
 *
 * ─── THE PHOTO THE PLANNER NAMED, THEN HER PICKS, THEN HER LIBRARY ─────────────────────────────
 *
 * Every castable item names the photo its direction was written about — a `ref` into `library`, the
 * list the planner was shown (studio/agent/types.ts `PlanItem.ref`; decided after device check
 * finding 6, where a basketball direction was cast onto a soccer photo by query). Pass 1 casts each
 * named photo that fits the item's kind and is not taken, BEFORE anything else — so no fallback can
 * take a photo another item was written about.
 *
 * An item whose named photo cannot be used is SWAPPED, and says so (`SWAPPED_LINE`): first to an
 * unused photo she picked that fits its kind — a pick beats a search hit, she chose it — then to her
 * library by its query. A pick is never forced into a kind it does not fit — a photo of her into
 * b-roll is a refusal seedance would give 6 times of 6, and an empty frame in an identity shot claims
 * she is somewhere she is not. The judgment on every path is `fitsKind`, on the row as OUR predicate
 * loaded it: a ref is a handle into rows already loaded under her athlete id, never an id.
 *
 * ─── HER PRODUCTS, IN THE ORDER SHE PICKED THEM ────────────────────────────────────────────────
 *
 * `product` items are her own picks, never searched, and ALL of them are spoken for before anything
 * else — a product photograph with nobody in it would otherwise be a perfectly good b-roll hit and
 * could turn up twice. The first product item takes her first product, the next the next; a product
 * item past the last of them is dropped and shown (`NO_PRODUCT_LEFT_LINE`), never given one twice.
 * The planner is told the same order (studio/agent/plan.ts), so each direction is about its own.
 *
 * ─── ANOTHER BRAND ON THE PHOTOGRAPH ──────────────────────────────────────────────────────────
 *
 * `avoid` is every sportswear brand her sentence did NOT name (studio/agent/brands.ts), empty when it
 * named none. Every cast photo showing one is FLAGGED ("This photo shows Nike."), never dropped: the
 * plan is hers to judge. A photo the planner named is its choice — it was shown each photo's brands and
 * asked to prefer a clean one — so the caster does not overrule it; on the query fallback, among the
 * photos that fit, a clean one is taken before a branded one. Her own picks and products are never
 * passed over for this — she chose them.
 *
 * An asset cast into one item is not offered to a later one — a board of the same photograph twice
 * is not a plan. A clip is the exception by construction: each BEAT of it is its own footage, so
 * the same clip may be cast once per beat (`cutKey`); the same beat twice, or the whole clip beside
 * one of its beats, is the reuse the rule refuses.
 */
/**
 * What "used" is keyed on. A photograph is one thing: its id. A clip is a FILE with windows — a beat
 * is one window, the whole clip is all of them — so a clip cut to beat [0] and the same clip cut to
 * beat [1] are two different pieces of footage, not a reuse (the plan eval already counts them so:
 * eval/metrics.ts `refsReused` keys on `ref#segment`). Found on device 22 Sep 2026: the planner
 * named d076a790's beats [0]–[3] on four items and the caster, keyed on the id alone, refused the
 * last three as "already used". The whole clip and any of its beats DO overlap, so one blocks the
 * other — a board that plays the whole clip and then its middle again is the reuse the rule is for.
 */
const cutKey = (assetId: string, segment: number | null) =>
  `${assetId}#${segment ?? "whole"}`;
const isUsed = (
  used: ReadonlySet<string>,
  assetId: string,
  segment: number | null,
): boolean => {
  if (used.has(cutKey(assetId, segment))) return true;
  if (used.has(cutKey(assetId, null))) return true; // the whole clip covers every beat
  if (segment === null)
    for (const k of used) if (k.startsWith(`${assetId}#`)) return true; // a beat blocks the whole
  return false;
};
/** The cut an item asks of a row: a beat index on a clip, null on a photograph or a whole clip. */
const cutOf = (row: { mediaType: LibraryMediaType }, segment: number | null) =>
  row.mediaType === "clip" ? segment : null;

/**
 * quality-scrappy piece 3: a cut's edge within half a second of a camera cut lands ON the cut (video/shotSnap.ts),
 * under STUDIO_SHOT_DETECT and only when boundaries are stored; otherwise the window comes back as chosen. The log line
 * is how the ledger counts firings. The caster's own snap — exported so the post-kit builder (agent/postKit/kit.ts)
 * cuts a clip exactly the way the caster does, never by a second copy of the rule.
 */
export function snapCut(
  assetId: string,
  chosen: { startSec: number; endSec: number },
  shots: readonly number[] | undefined,
  durationSeconds: number | null,
): { startSec: number; endSec: number } {
  if (!shotDetectEnabled() || !shots?.length) return chosen;
  const snapped = snapWindow(chosen, shots, { durationSec: durationSeconds });
  if (snapped.snapped.length)
    logger.info(
      {
        assetId,
        edges: snapped.snapped,
        from: chosen,
        to: { startSec: snapped.startSec, endSec: snapped.endSec },
      },
      "cut snapped to a shot boundary",
    );
  return { startSec: snapped.startSec, endSec: snapped.endSec };
}

/**
 * Each photo's chain root, under HER athlete id (referenceGate.ts `CHAIN_ROOT_SQL`) — read only with
 * STUDIO_LIBRARY_FIELDS on, the chain rule's own flag; off, nothing is read and every photo is its own root, as before.
 */
async function chainRoots(
  athleteId: string,
  ids: readonly string[],
): Promise<Map<string, string>> {
  if (!libraryFieldsEnabled() || ids.length === 0) return new Map();
  const rows = await db
    .select({
      id: mediaAssets.id,
      root: sql<string>`${sql.raw(CHAIN_ROOT_SQL)}`,
    })
    .from(mediaAssets)
    .where(
      and(
        eq(mediaAssets.athlete_id, athleteId),
        inArray(mediaAssets.id, [...ids]),
      ),
    );
  return new Map(rows.map((r) => [r.id, r.root ?? r.id]));
}

export async function castPlan(
  athleteId: string,
  plan: AgentPlan,
  given: {
    /** Her products, in the order she picked them. */
    products: CastPick[];
    /** The library the planner was shown, by ref — the only photos a `ref` may name. */
    library: ReadonlyMap<string, CastableRow>;
    picks: CastPick[];
    /** Brands a photograph should not show for her sentence — required, so every caller decides. */
    avoid: readonly Brand[];
    /**
     * Her sentence asks for her own footage (studio/agent/footageAsk.ts) — S1b: a made-here still is
     * refused for every photo kind unless she picked it. Absent means no, as before.
     */
    ownFootage?: boolean;
  },
  search: CastSearch = searchMedia,
  poster: BeatPoster = beatPosterUrl,
): Promise<CastPlan> {
  const { products, library, picks, avoid } = given;
  const ownFootage = given.ownFootage === true;
  /** Shows none of the brands she did not name. */
  const clean = (vision: Record<string, unknown> | null) =>
    brandsShown(brandsOf(vision), avoid).length === 0;
  // Every product is spoken for before anything else — see the header.
  const used = new Set<string>(products.map((p) => cutKey(p.assetId, null)));
  let nextProduct = 0;
  /** What she picked herself — a pick passes S1's provenance gate on i2v, wherever it is cast from. */
  const pickedIds = new Set(picks.map((p) => p.assetId));

  // ─── ONE PHOTO, HOWEVER MANY EDITS (PR 19, the walk's shots 3 and 4) ──────────────────────────────────────────────
  //
  // `used` is keyed on the id, so an upload and its made-here edit — two ids, one photograph — could both be cast, and
  // since the chain rule (ADI-R19-BOARD) an edit of her photo can be an i2v unpicked: the walk's board animated an edit
  // (shot 3) beside the photo it was made from (shot 4). So a PHOTO is also keyed on its chain root: a photo and every
  // edit in its `derived_from` chain are one photo, cast once — twice only when she picked it twice (every holder of
  // the root, and this one, her picks; her products count as picks). ⚠️ MUTATION M-oneChain: `rootBlocks` answers
  // false — "a photo and its edit are one photo: the caster casts it once" reds by name.
  const roots = await chainRoots(athleteId, [
    ...products.map((p) => p.assetId),
    ...picks.map((p) => p.assetId),
    ...[...library.values()].map((r) => r.id),
  ]);
  const rootOf = (id: string) => roots.get(id) ?? id;
  /** Each root cast so far → true while every holder of it was her pick. */
  const rootHeld = new Map<string, boolean>();
  const claimRoot = (id: string, picked: boolean) =>
    rootHeld.set(rootOf(id), (rootHeld.get(rootOf(id)) ?? true) && picked);
  const rootBlocks = (id: string, picked: boolean): boolean => {
    const held = rootHeld.get(rootOf(id));
    return held !== undefined && !(held && picked);
  };
  for (const p of products) claimRoot(p.assetId, true);

  // ── Pass 1: the photo each item was written about, before any fallback can take it ──────────
  const named = new Map<number, CastableRow>();
  /** Why a castable item's ref was NOT reserved — the first half of its left-out reason. */
  const namedWhy = new Map<number, string>();
  /** Which item took a cut (`cutKey`), for the reason line. */
  const usedBy = new Map<string, number>();
  /** The item holding the cut that blocks `assetId#cut`: the same cut, else the whole, else the first beat. */
  const heldBy = (assetId: string, cut: number | null): number | undefined =>
    usedBy.get(cutKey(assetId, cut)) ??
    usedBy.get(cutKey(assetId, null)) ??
    [...usedBy.entries()].find(([k]) => k.startsWith(`${assetId}#`))?.[1];
  plan.items.forEach((item, i) => {
    if (!(CASTABLE_KINDS as readonly string[]).includes(item.kind)) return;
    if (!item.ref) {
      namedWhy.set(i, "no_ref");
      return;
    }
    const row = library.get(item.ref);
    if (!row) {
      namedWhy.set(i, `ref_not_in_library(${item.ref})`);
      return;
    }
    const cut = cutOf(row, item.segment);
    if (
      row.mediaType === "photo" &&
      !isUsed(used, row.id, cut) &&
      rootBlocks(row.id, pickedIds.has(row.id))
    ) {
      namedWhy.set(i, `ref_same_photo_as_used(${item.ref})`);
      return;
    }
    if (isUsed(used, row.id, cut)) {
      const by = heldBy(row.id, cut);
      namedWhy.set(
        i,
        `ref_already_used(${item.ref}#${cut ?? "whole"} by ${by === undefined ? "a product" : `item ${by}`})`,
      );
      return;
    }
    if (
      !fitsKind(item.kind, row, { picked: pickedIds.has(row.id), ownFootage })
    ) {
      namedWhy.set(
        i,
        `ref_kind_mismatch(${item.ref} is a ${row.mediaType}${row.mediaType === "clip" && ownFootage ? `, provenance ${row.provenance ?? "unknown"}, own_footage` : ""}${row.mediaType === "photo" ? `, athlete_present ${row.athletePresent}, provenance ${row.provenance ?? "unknown"}, identity_bound ${row.identityBound ?? "unknown"}${row.meta ? ", meta_image" : ""}${ownFootage ? ", own_footage" : ""}` : ""})`,
      );
      return;
    }
    used.add(cutKey(row.id, cut));
    usedBy.set(cutKey(row.id, cut), i);
    if (row.mediaType === "photo") claimRoot(row.id, pickedIds.has(row.id));
    named.set(i, row);
  });

  // ── Pass 2: every item in order — its named photo, else swapped: a pick, else her library ────
  const items: CastItem[] = [];
  const leftOut: LeftOut[] = [];
  for (const [i, item] of plan.items.entries()) {
    // Capabilities with no Board slot travel as prose on the direction — the place freeform camera
    // language lived before the vocabulary existed. Slotted ones ride as `shot`.
    const prose = capabilityProse(item.capabilities);
    const shot = toShotSpec(item.capabilities);
    const base = {
      kind: item.kind,
      beat: item.beat,
      direction: prose ? `${item.direction} ${prose}` : item.direction,
      sound: item.sound,
      motion: item.kind === "image" ? item.motion : null,
      focus: item.kind === "image" ? (item.focus ?? null) : null,
      reason: item.reason ?? null,
      ...(item.capabilities ? { capabilities: item.capabilities } : {}),
      ...(shot ? { shot } : {}),
    };
    const uncast = (
      line: string | null = UNCAST_LINE,
      fallback: string | null = null,
    ): CastItem => {
      // A null line is b-roll made from words — not left out, so no reason.
      if (line !== null)
        leftOut.push({
          index: i,
          kind: item.kind,
          ref: item.ref,
          segment: item.segment,
          reason: [namedWhy.get(i), fallback].filter(Boolean).join("; "),
        });
      // A dropped i2v written about other people: the words go with the photo. Its beat is what
      // she reads where the direction was (REWRITTEN_LINE).
      const scrub =
        line !== null &&
        item.kind === "i2v" &&
        mentionsOtherPeople(item.direction);
      return {
        ...base,
        ...(scrub ? { direction: item.beat } : {}),
        rewritten: scrub ? REWRITTEN_LINE : null,
        demoted: null,
        assetId: null,
        thumbUrl: null,
        athletePresent: null,
        brandFlag: null,
        swapped: null,
        uncast: line,
        mediaType: null,
        trim: null,
        durationSeconds: null,
        videoUrl: null,
        provenance: null,
        platform: null,
        editNote: null,
      };
    };
    // A clip's window is the beat the planner named — on the clip it named — or the seconds INSIDE
    // that beat it asked for (`window`, already clamped by the parser; re-checked here against the
    // beat as this row holds it). On a SWAPPED clip the segment means nothing (it indexed another
    // clip's beats), so the whole clip goes in.
    const trimFor = (pick: CastPick, swapped: string | null) => {
      if (
        pick.mediaType !== "clip" ||
        swapped !== null ||
        item.segment === null
      )
        return null;
      const b = pick.beats[item.segment];
      if (!b) return null;
      const w = item.window;
      const chosen =
        w &&
        w.startSec >= b.startSec &&
        w.endSec <= b.endSec &&
        w.endSec > w.startSec
          ? { startSec: w.startSec, endSec: w.endSec }
          : { startSec: b.startSec, endSec: b.endSec };
      return snapCut(pick.assetId, chosen, pick.shots, pick.durationSeconds);
    };
    const castTo = async (
      pick: CastPick,
      swapped: string | null,
    ): Promise<CastItem> => {
      const trim = trimFor(pick, swapped);
      // A beat row shows a frame from INSIDE its window, not the clip's frame 0 (beatPoster.ts).
      // Null — not made, for any reason — keeps the clip's poster.
      const beatFrame =
        trim && pick.videoPath
          ? await poster({
              athleteId,
              assetId: pick.assetId,
              videoPath: pick.videoPath,
              window: trim,
            })
          : null;
      // A swapped i2v written about other people: the direction was about the photo that left,
      // so it becomes the photo that arrived — its own line (else the beat), with the capability
      // prose kept. Never on the planned photo, never on a clip or a held image.
      const scrub =
        swapped !== null &&
        item.kind === "i2v" &&
        mentionsOtherPeople(item.direction);
      const fallback = pick.description?.trim() || item.beat;
      // Rule 1's demotion, where code can read it (A1b): on an own-footage brief her camera covers
      // the moment by her own words, so the photo is HELD, pushed in — the same photo the i2v gates
      // chose, never a different one. Only the kind and the motion change; nothing is generated.
      // ⚠️ MUTATION (cast.test, studio.agent.test): drop `ownFootage &&`'s effect — the i2v stays an
      // i2v on an own-footage brief — and "held, not animated" reds by name.
      const demote = ownFootage && item.kind === "i2v";
      return {
        ...base,
        ...(scrub
          ? { direction: prose ? `${fallback} ${prose}` : fallback }
          : {}),
        ...(demote ? { kind: "image" as const, motion: "dolly" as const } : {}),
        rewritten: scrub ? REWRITTEN_LINE : null,
        demoted: demote ? DEMOTED_LINE : null,
        assetId: pick.assetId,
        thumbUrl: beatFrame ?? pick.thumbUrl,
        athletePresent: pick.athletePresent,
        brandFlag: brandFlag(pick.brandsVisible, avoid),
        swapped,
        uncast: null,
        mediaType: pick.mediaType,
        trim,
        durationSeconds:
          pick.mediaType === "clip" ? pick.durationSeconds : null,
        videoUrl: pick.mediaType === "clip" ? (pick.videoUrl ?? null) : null,
        provenance: pick.provenance ?? null,
        platform: pick.platform ?? null,
        editNote: pick.mediaType === "clip" ? (pick.editNote ?? null) : null,
      };
    };

    // B-ROLL IS MADE FROM WORDS: no photo, no search, no swap — and not left out (null line). See
    // the header. Whatever ref a model sent for it was already dropped by parsePlan.
    if (item.kind === "broll") {
      items.push(uncast(null));
      continue;
    }

    if (item.kind === "product") {
      const product = products[nextProduct];
      if (product) {
        nextProduct += 1;
        items.push(await castTo(product, null));
      } else {
        items.push(uncast(NO_PRODUCT_LEFT_LINE, "no_product_left"));
      }
      continue;
    }
    if (!(CASTABLE_KINDS as readonly string[]).includes(item.kind)) {
      items.push(uncast(UNCAST_LINE, "kind_not_castable"));
      continue;
    }

    const planned = named.get(i);
    if (planned) {
      items.push(await castTo(await asPick(planned), null));
      continue;
    }

    // ── Swapped from here on: the named photo could not be used ─────────────────────────────────
    const pick = picks.find(
      (p) =>
        !isUsed(used, p.assetId, null) &&
        !(p.mediaType === "photo" && rootBlocks(p.assetId, true)) &&
        fitsKind(item.kind, p, { picked: true, ownFootage }),
    );
    if (pick) {
      used.add(cutKey(pick.assetId, null));
      if (pick.mediaType === "photo") claimRoot(pick.assetId, true);
      items.push(await castTo(pick, SWAPPED_LINE));
      continue;
    }
    // A CLIP IS NEVER SEARCHED FOR — see UNCAST_CLIP_LINE. Left out, and shown.
    if (item.kind === "clip") {
      items.push(uncast(UNCAST_CLIP_LINE, "no_pick_fits; clip_never_searched"));
      continue;
    }

    const query = item.searchQuery ?? item.direction;
    const results = await search(athleteId, {
      brief: query,
      // A hint to the ranking only — it is truthy-only and passes untagged rows. The judging is
      // `fitsKind`, below, on the row as OUR predicate loaded it.
      filters: { athletePresent: true },
      k: CAST_CANDIDATES,
    });
    const rows = await loadCastable(
      athleteId,
      results.map((r) => r.id),
    );
    for (const [id, root] of await chainRoots(
      athleteId,
      results.map((r) => r.id).filter((id) => !roots.has(id)),
    ))
      roots.set(id, root);

    // searchMedia's order is the ranking; our predicate is the verdict; a clean photograph first.
    const fitting = results.filter((r) => {
      const row = rows.get(r.id);
      return (
        row !== undefined &&
        !isUsed(used, r.id, null) &&
        !(row.mediaType === "photo" && rootBlocks(r.id, false)) &&
        fitsKind(item.kind, row, { ownFootage })
      );
    });
    // On an own-footage brief the best provenance first — her camera, then her synced accounts,
    // then made here (doctrine rule 3's order, PR 4 B2b) — and a clean photograph within that group.
    // Off one, the search's order alone, as before. ⚠️ MUTATION (cast.test): drop the grouping —
    // "camera before her instagram" reds by name.
    const rankOf = (id: string) => ownFootageRank(rows.get(id)!.provenance);
    const top = Math.min(...fitting.map((r) => rankOf(r.id)));
    const best = ownFootage
      ? fitting.filter((r) => rankOf(r.id) === top)
      : fitting;
    const hit = best.find((r) => clean(rows.get(r.id)!.vision)) ?? best[0];

    if (hit) {
      const row = rows.get(hit.id)!;
      used.add(cutKey(hit.id, null));
      if (row.mediaType === "photo") claimRoot(hit.id, false);
      items.push(
        await castTo(
          {
            assetId: hit.id,
            thumbUrl: hit.url,
            athletePresent: row.athletePresent,
            brandsVisible: brandsOf(row.vision),
            mediaType: row.mediaType,
            durationSeconds: row.durationSeconds,
            beats: row.beats,
            videoUrl: hit.videoUrl,
            videoPath: row.videoPath,
            provenance: row.provenance,
            platform: row.platform,
            editNote: row.editNote,
            identityBound: row.identityBound,
            description:
              typeof row.vision?.description === "string"
                ? row.vision.description
                : null,
          },
          SWAPPED_LINE,
        ),
      );
    } else {
      items.push(uncast(UNCAST_LINE, "no_pick_fits; no_search_hit"));
    }
  }

  // Made = everything but what was left out: a photo item, or b-roll from words.
  return {
    items,
    castCount: items.filter((i) => i.uncast === null).length,
    leftOut,
  };
}
