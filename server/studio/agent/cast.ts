/** One candidate as our own predicate saw it. */
export interface CastableRow {
  id: string;
  /** vision.athlete_present — or null when the row carries no such tag. Never guessed. */
  athletePresent: boolean | null;
  /** thumb ?? path: what a surface shows for it. */
  gcsPath: string | null;
  /** A clip's mp4 (`gcs_path`) — what plays, and what a beat's frame is read from. Null on a photo. */
  videoPath: string | null;
  /** Signal 1 (studio/enrich/provenanceSignal.ts) — `metadata.provenance_signal.signal`, or null when never probed. */
  provenanceSignal: "device-camera" | "no-device-metadata" | "unknown" | null;

  /**
   * The vision tags as enrichment wrote them (lib/visionTag.ts), or null when there are none. What
   * the route describes a photograph to the planner with — MODEL-WRITTEN TEXT, which the planner
   * fences as data (studio/agent/plan.ts).
   */
  vision: Record<string, unknown> | null;
  /** Where it came from (studio/agent/provenance.ts) — a label on the planner's line, never a rank. */
  provenance: Provenance | null;
  /** `media_assets.platform` — which account a synced row came off ("instagram"), for its label (PR 4 B2b). */
  platform: string | null;
  /** A photograph (herPhoto) or a clip (herClip) — the two arms of the one door this row came through. */
  mediaType: LibraryMediaType;
  /** A clip's measured length (duration_seconds_precise, else the upload's whole seconds), or null. */
  durationSeconds: number | null;
  /** A clip's beats as Half A wrote them (vision.beats), already clamped; [] on a photo. */
  beats: {
    startSec: number;
    endSec: number;
    description: string;
    camera: string;
    motion: string;
  }[];
  /**
   * quality-scrappy piece 3: a clip's shot boundaries (`metadata.shots`, video/shots.ts), seconds, ascending. ABSENT
   * when none are stored — so a row read before STUDIO_SHOT_DETECT ever ran is the row it was.
   */
  shots?: number[];
  /**
   * The tagger's own edit for a CLIP — `vision.edit_note` when its `disposition` is "crop" or
   * "enhance" (studio/enrich/videoTag.ts), else null. Read, never generated: the note the clip lane
   * already stored, surfaced on the plan card as an AI-edit chip (C3, D1). Null on a photo and on a
   * clip the tagger passed as it is or rejected.
   */
  editNote: string | null;
  /**
   * S2 — whether the job that generated this row carried a reference of HER (`person` role on the
   * frozen brief): true / false for a job of hers, null when no job of hers is on the row. Read
   * through the join in `CASTABLE_COLUMNS`; the one fact that says a generated face was hers by
   * construction. Only `true` lets a made-here still be an i2v ref unpicked (`fitsKind`).
   */
  identityBound: boolean | null;
  /**
   * A2 — a META image (`isMetaImage`): a text graphic, a screenshot, a mockup, an abstract colour
   * block. Something ABOUT her media, not a photograph of a moment. Never held or animated unless she
   * picked it (`fitsKind`). Always false on a clip.
   */
  meta: boolean;
}

/**
 * A2 (PR 4) — the words that make a photograph a meta image, in the tagger's own description or
 * setting. A CLOSED list on purpose: "graphic background" is a real studio portrait of her and "text
 * overlay" is a campaign still (rule 2's sign-off) — neither is here. Found in her library, 22 Sep
 * 2026: two made-here Instagram screenshots (one pushed in as "the aftermath" on a live brief), a
 * smartphone mockup, and three colour-block graphics.
 */
const META_WORDS =
  /\b(?:screen ?shots?|screen ?grabs?|screen ?captures?|mock-?ups?|(?:smart)?phone frame|abstract (?:graphic|colou?r|art|shapes?)|colou?r[- ]blocks?|split colou?rs?|solid colou?rs?)\b/i;

/** A text graphic by the tagger's shot_type, or a meta image by its words. Never true on a clip. */
export const isMetaImage = (
  vision: Record<string, unknown> | null,
  isVideo = false,
): boolean => {
  if (isVideo || !vision) return false;
  if (vision.shot_type === "text_graphic") return true;
  const words = [vision.description, vision.setting]
    .filter((v): v is string => typeof v === "string")
    .join(" ");
  return META_WORDS.test(words);
};

/** The tagger's dispositions that carry an edit worth showing — "as_is" has none, "reject" is not an edit. */
export const EDITABLE_DISPOSITIONS: readonly string[] = ["crop", "enhance"];

/** `vision.edit_note` when the disposition says there is an edit — a short line, capped; else null. */
export const editNoteOf = (
  vision: Record<string, unknown> | null,
  isVideo: boolean,
): string | null => {
  if (!isVideo || !vision) return null;
  const disposition = vision.disposition;
  const note = vision.edit_note;
  if (
    typeof disposition !== "string" ||
    !EDITABLE_DISPOSITIONS.includes(disposition) ||
    typeof note !== "string"
  )
    return null;
  const t = capWords(note, 200);
  return t || null;
};

/**
 * THE PREDICATE. Every asset this module may hand back passes through here, under her athlete id —
 * hers · stored · not deleted · top-level · a photograph OR a clip (C2 Half B: a plan may name a
 * clip). Both arms live in studio/photoPredicate.ts so the stitch can resolve a still or a clip
 * through the same ones without importing this module's model calls. `rankWithoutHer` narrows to
 * photographs: a scene is shown as context for b-roll, and a clip is not a scene.
 */
const castable = herPhotoOrClip;

const IDENTITY_BOUND_COLUMN: SQLWrapper = {
  getSQL: () =>
    libraryFieldsEnabled()
      ? sql`(${sql.raw(CHAIN_IDENTITY_BOUND_SQL)})`
      : sql`CASE WHEN ${generationJobs.id} IS NULL THEN NULL ELSE ${sql.raw(jobIdentityBoundOf('"generation_jobs"."brief"'))} END`,
};

const CASTABLE_COLUMNS = {
  id: mediaAssets.id,
  metadata: mediaAssets.metadata,
  thumb: mediaAssets.gcs_thumb_path,
  path: mediaAssets.gcs_path,
  origin: mediaAssets.origin,
  platform: mediaAssets.platform,
  mediaType: mediaAssets.media_type,
  precise: mediaAssets.duration_seconds_precise,
  whole: mediaAssets.duration_seconds,
  // What tells a stitched compilation from a generated clip (provenance.ts `provenanceOfRow`).
  generationJobId: mediaAssets.generation_job_id,
  // S2: did the job that made this row carry a reference of her? Null when the join missed — no
  // job on the row, or a job that is not hers (`castableFrom` puts the athlete on the join). With
  // STUDIO_LIBRARY_FIELDS on, the chain rule (ADI-R19-BOARD) — the SAME expression the tiles and the
  // media ranking read, so an edit of her upload is hers here too (S2). Read per query.
  identityBound: sql<boolean | null>`${IDENTITY_BOUND_COLUMN}`,
};

/**
 * The one SELECT every castable row comes through: the columns above, off media_assets, with the
 * generating job joined READ-ONLY and under HER athlete id — the fail-safe studio/content.ts uses
 * for the same bare uuid. Every reader in this module (`loadCastable`, `listClips`,
 * `rankWithoutHer`) starts here, so no reader can forget the athlete on the join.
 */
const castableFrom = (athleteId: string) =>
  db
    .select(CASTABLE_COLUMNS)
    .from(mediaAssets)
    .leftJoin(
      generationJobs,
      and(
        eq(mediaAssets.generation_job_id, generationJobs.id),
        eq(generationJobs.athlete_id, athleteId),
      ),
    );

/**
 * NOT a stitched compilation — the SQL twin of provenance.ts `provenanceOfRow`'s stitched arm, for
 * `listClips`. A compilation is never OFFERED to the planner: on device, "use my real footage" cast
 * one (holding a branded segment) as "your clip", and that is a trust problem the prompt may not be
 * left to hold alone. cast.test.ts holds the two forms agree on every shape of row.
 */
/** camera 0 · synced 1 · made-here 2 — the same fold as provenance.ts PROVENANCE_OF_ORIGIN, as an ORDER BY. */
const clipProvenanceRank = sql`CASE ${mediaAssets.origin} WHEN 'upload' THEN 0 WHEN 'connected' THEN 1 WHEN 'discovery' THEN 1 ELSE 2 END`;

const notStitchedHere = sql`NOT (${mediaAssets.origin} = 'generated' AND (${mediaAssets.generation_job_id} IS NULL OR ${mediaAssets.gcs_path} LIKE '%/studio/stitch/%'))`;

const num = (v: unknown): number | null =>
  typeof v === "number" && Number.isFinite(v) ? v : null;

/** Half A's beats off the vision object — only well-formed ones, in order. */
function beatsOf(vision: Record<string, unknown> | null): CastableRow["beats"] {
  const raw = vision?.beats;
  if (!Array.isArray(raw)) return [];
  const out: CastableRow["beats"] = [];
  for (const b of raw) {
    if (!b || typeof b !== "object") continue;
    const r = b as Record<string, unknown>;
    const startSec = num(r.start_s);
    const endSec = num(r.end_s);
    if (startSec === null || endSec === null || endSec <= startSec) continue;
    out.push({
      startSec,
      endSec,
      description: typeof r.description === "string" ? r.description : "",
      camera: typeof r.camera === "string" ? r.camera : "",
      motion: typeof r.motion === "string" ? r.motion : "",
    });
  }
  return out;
}

/** One row as the predicate loaded it — the tags read, never guessed. */
function toCastable(r: {
  id: string;
  metadata: unknown;
  thumb: string | null;
  path: string | null;
  origin: string | null;
  platform: string | null;
  mediaType: string;
  precise: number | null;
  whole: number | null;
  generationJobId: string | null;
  identityBound: boolean | null;
}): CastableRow {
  const raw = (r.metadata as { vision?: unknown } | null)?.vision;
  const vision =
    raw && typeof raw === "object" && !Array.isArray(raw)
      ? (raw as Record<string, unknown>)
      : null;
  const present = vision?.athlete_present;
  const sig = (
    r.metadata as { provenance_signal?: { signal?: unknown } } | null
  )?.provenance_signal?.signal;
  return {
    id: r.id,
    provenanceSignal:
      sig === "device-camera" ||
      sig === "no-device-metadata" ||
      sig === "unknown"
        ? sig
        : null,
    athletePresent: typeof present === "boolean" ? present : null,
    gcsPath: r.thumb ?? r.path ?? null,
    videoPath: VIDEO_TYPES.includes(r.mediaType) ? (r.path ?? null) : null,
    vision,
    provenance: provenanceOfRow({
      origin: r.origin,
      isVideo: VIDEO_TYPES.includes(r.mediaType),
      generationJobId: r.generationJobId,
      gcsPath: r.path,
    }),
    platform: r.platform ?? null,
    mediaType: VIDEO_TYPES.includes(r.mediaType) ? "clip" : "photo",
    durationSeconds: r.precise ?? (r.whole && r.whole > 0 ? r.whole : null),
    beats: VIDEO_TYPES.includes(r.mediaType) ? beatsOf(vision) : [],
    ...(VIDEO_TYPES.includes(r.mediaType) && shotsOf(r.metadata).length
      ? { shots: shotsOf(r.metadata) }
      : {}),
    editNote: editNoteOf(vision, VIDEO_TYPES.includes(r.mediaType)),
    identityBound:
      typeof r.identityBound === "boolean" ? r.identityBound : null,
    meta: isMetaImage(vision, VIDEO_TYPES.includes(r.mediaType)),
  };
}

/**
 * These ids, through THE PREDICATE.
 *
 * Also what the route loads her hand-picked products and photos through, so a product she "picked"
 * that is not hers, is deleted, or is a video, is refused at the same door.
 */
export async function loadCastable(
  athleteId: string,
  ids: string[],
): Promise<Map<string, CastableRow>> {
  if (ids.length === 0) return new Map();
  const rows = await castableFrom(athleteId).where(
    castable(athleteId, inArray(mediaAssets.id, [...new Set(ids)])),
  );
  return new Map(rows.map((r) => [r.id, toCastable(r)]));
}

/**
 * Her CLIPS that have been read as clips — through `herClip`, tagged rows only, never a stitched
 * compilation (`notStitchedHere`), her camera first and newest within, at most `limit`. What the
 * planner is shown under CLIP lines (C2 Half B; the provenance order is the doctrine PR's).
 *
 * searchMedia ranks photographs by a hero score a clip never earns, so clips are listed here and
 * not searched for. A clip whose read found no beats is still offered (whole clip only, and its
 * line says so).
 */
export async function listClips(
  athleteId: string,
  limit: number,
): Promise<CastableRow[]> {
  if (limit <= 0) return [];
  const rows = await castableFrom(athleteId)
    .where(
      herClip(
        athleteId,
        sql`${mediaAssets.metadata} -> 'vision' IS NOT NULL`,
        notStitchedHere,
      ),
    )
    // HER CAMERA FIRST, then synced, then made-here — newest within each (doctrine, 22 Sep 2026).
    // The baseline showed why newest-first alone fails "real footage first": her uploads are older
    // than every generated clip, so 85 of 88 CLIP lines the planner saw were made-here and "use my
    // real footage" came back as six generated clips. A prompt rule cannot prefer what is not offered.
    .orderBy(
      clipProvenanceRank,
      desc(mediaAssets.ingested_at),
      desc(mediaAssets.id),
    )
    .limit(limit);
  return rows.map(toCastable);
}

/**
 * Her photographs WITHOUT her in them, best match for `query` first — through THE PREDICATE, and
 * only rows the tagger said `athlete_present: false` about (an untagged row is not a scene).
 *
 * ─── ⚠️  WHY THESE ARE RANKED HERE AND NOT BY searchMedia ────────────────────────────────────────
 *
 * searchMedia's default score is `0.7·similarity + 0.3·(0.6·hero + 0.4·views)`, and `heroScore` is
 * 0 for any photo without her in it (lib/visionTag.ts). So every photo of her carries up to 0.18 a
 * scene can never earn, and on a real library — 358 photos of her, 7 without (device check,
 * 21 Sep 2026) — a scene reaches the top of the list only when it matches almost exactly. That is
 * right for the hero shots searchMedia was built to pick, and wrong for showing the planner her scenes:
 * ranked by searchMedia it would never have seen one. (B-roll itself is made from words now; scenes
 * are shown to the planner as context only.)
 *
 * So scenes are ranked AMONG THEMSELVES, by the same similarity searchMedia uses (the row's stored
 * embedding against `embedText(query)`) and nothing else. searchMedia is shared and not changed.
 *
 * One `embedText`. A row with no embedding ranks after every row with one; if the query cannot be
 * embedded, the rows come back in the database's order rather than not at all.
 */
export async function rankWithoutHer(
  athleteId: string,
  query: string,
): Promise<CastableRow[]> {
  const rows = await castableFrom(athleteId).where(
    herPhoto(
      athleteId,
      sql`${mediaAssets.metadata} -> 'vision' -> 'athlete_present' = 'false'::jsonb`,
    ),
  );
  if (rows.length === 0) return [];
  const q = await embedText(query);
  const score = (r: (typeof rows)[number]) => {
    const emb = (r.metadata as { embedding?: unknown } | null)?.embedding;
    return q && Array.isArray(emb) ? cosine(q, emb as number[]) : -Infinity;
  };
  // Compared, not subtracted: two unembedded rows are -Infinity each, and -Infinity minus itself is
  // NaN, which leaves a sort's order undefined.
  return rows
    .map((r) => ({ row: toCastable(r), score: score(r) }))
    .sort((a, b) => (a.score === b.score ? 0 : a.score > b.score ? -1 : 1))
    .map((x) => x.row);
}

/**
 * Doctrine rule 3's order on an own-footage brief (PR 4 B2b): her camera, then her synced accounts
 * (a reel she posted), then made here. The cast's swap takes the best group first; `listClips`
 * already offers clips in this order (`clipProvenanceRank`).
 */
export const OWN_FOOTAGE_ORDER: readonly Provenance[] = [
  "camera",
  "synced",
  "made-here",
];
const ownFootageRank = (p: Provenance | null): number => {
  const i = p === null ? -1 : OWN_FOOTAGE_ORDER.indexOf(p);
  return i === -1 ? OWN_FOOTAGE_ORDER.length : i;
};

/** The provenances that are hers by construction — an i2v ref may come from these unpicked (S1). */
export const I2V_PROVENANCES: readonly Provenance[] = ["camera", "synced"];

/**
 * Whether a row may be cast into a kind. See the header: the equality is the untagged guard.
 *
 * `i2v` and `image` are cast from her library (CASTABLE_KINDS). Only a photo she is KNOWN to be in
 * fits `i2v` — and, since S1, only one that is hers by provenance (camera, synced) or one she
 * PICKED (`picked`): a made-here still is never animated as her on the tagger's word alone. An
 * `image` is the photo held as it is — a product close-up, a place, her — so any of her
 * photographs fits it, tagged or not: nothing is generated from it, so the untagged guard has
 * nothing to guard. There is no b-roll arm any more — b-roll is made from words and nothing is cast
 * into it.
 */
export const fitsKind = (
  kind: PlanItemKind,
  row: Pick<CastableRow, "athletePresent" | "mediaType"> & {
    provenance?: Provenance | null;
    /** S2: the generating job carried a reference of her. Absent on an older caller's pick: unknown. */
    identityBound?: boolean | null;
    /** A2: a text graphic, screenshot, mockup or colour block. Absent on an older caller's pick: not meta. */
    meta?: boolean;
    /** PR 12: the row's vision tags, for `disposition`. Absent on an older caller's pick: not a reject. */
    vision?: Record<string, unknown> | null;
  },
  given: {
    /** She picked this row herself for this plan — her decision outranks the provenance gate. */
    picked?: boolean;
    /** S1b / S1c: her sentence asks for her own footage — every photo kind, and every clip, takes S1's gate. */
    ownFootage?: boolean;
  } = {},
): boolean => {
  const picked = given.picked === true;
  const ownFootage = given.ownFootage === true;
  // PR 12 (ruling 3): a row the tagger set down as `reject` is on the planner's list with its label,
  // but is never AUTO-cast — not by the planner's ref, not by the search fallback. Only her own pick
  // of it casts. ⚠️ MUTATION (cast.test "planner sees a reject-disposition photo"): drop this line —
  // reds by name.
  if (libraryFieldsEnabled() && !picked && row.vision?.disposition === "reject")
    return false;
  // Hers by construction, or her own decision (S1).
  const hers =
    picked ||
    (row.provenance !== null &&
      row.provenance !== undefined &&
      I2V_PROVENANCES.includes(row.provenance));
  // S1c (PR 6): on an own-footage brief a CLIP is hers — her camera, her synced accounts — or one she
  // picked. The photo gates' promise, made for clips: a made-here clip opened every acceptance-recap
  // cell on 2bedd2e (docs/probes/capabilities.md, B_recap). Off one, any clip of hers fits, as before.
  // ⚠️ MUTATION (cast.test, studio.agent.test): drop `(!ownFootage || hers)` — "made-here clip
  // castable on own footage" reds by name.
  if (kind === "clip") return row.mediaType === "clip" && (!ownFootage || hers);
  if (row.mediaType === "clip") return false;
  // A2: a meta image is about her media, not a moment of her — never held, never animated, unless
  // she picked it. ⚠️ MUTATION (cast.test): drop this line — "meta images castable" reds by name.
  if (row.meta === true && !picked) return false;
  if (kind === "image") return ownFootage ? hers : true;
  return (
    kind === "i2v" &&
    row.athletePresent === true &&
    (hers ||
      // S2: made here FROM her — the job's frozen brief carried a person reference. Not on an
      // own-footage brief (S1b): a still generated from her is still not what she filmed.
      (!ownFootage &&
        row.provenance === "made-here" &&
        row.identityBound === true))
  );
};

